"""Generates ``sp24_v2.py``: straight-line Triton kernels for MXFP8 quantization fused with 2:4 compression.

No in-register reshapes: each 4-group element is its own strided load (L1 serves the shared lines), so Triton keeps one
blocked layout throughout. Kernels:
- ``sp24_rows``: plain 2:4 along K (per-row top-2 of 4 by |x|), one 64-column scale block per program column.
- ``sp24t``: transposable 2:4 (the optimal of the 90 4x4 patterns, exact, by meet-in-the-middle over row pairs) on a
  64 x 64 tile; emits the 2:4-along-K operand and the 2:4-along-M operand, each MXFP8 with 64-element scales.
Metadata here is one nibble per byte (2x the bytes of the hardware's packed format), so times are upper bounds.
"""

import itertools
import os

PAIRS = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]

HEADER = '''# Copyright The Marin Authors
# SPDX-License-Identifier: Apache-2.0

# Generated by gen_sp24.py; do not edit.
import torch
import triton
import triton.language as tl


@triton.jit
def _exponent(amax):
    bits = (amax / 448.0).to(tl.int32, bitcast=True)
    e = ((bits >> 23) & 0xFF) + ((bits & 0x7FFFFF) != 0).to(tl.int32)
    e = tl.minimum(tl.maximum(e, 1), 254)
    return tl.where(amax > 0, e, 127)


@triton.jit
def _scale_of(e):
    return (e << 23).to(tl.float32, bitcast=True)


@triton.jit
def _q8(v, sc):
    return (v / sc).to(tl.float8e4nv).to(tl.uint8, bitcast=True).to(tl.int32)


@triton.jit
def _top2(a0, a1, a2, a3):
    v0, v1, v2, v3 = tl.abs(a0), tl.abs(a1), tl.abs(a2), tl.abs(a3)
    b0 = (v1 > v0).to(tl.int32) + (v2 > v0).to(tl.int32) + (v3 > v0).to(tl.int32)
    b1 = (v0 >= v1).to(tl.int32) + (v2 > v1).to(tl.int32) + (v3 > v1).to(tl.int32)
    b2 = (v0 >= v2).to(tl.int32) + (v1 >= v2).to(tl.int32) + (v3 > v2).to(tl.int32)
    b3 = (v0 >= v3).to(tl.int32) + (v1 >= v3).to(tl.int32) + (v2 >= v3).to(tl.int32)
    return b0 < 2, b1 < 2, b2 < 2, b3 < 2


@triton.jit
def _compress4(a0, a1, a2, a3, k0, k1, k2, k3):
    first = tl.where(k0, a0, tl.where(k1, a1, a2))
    i0 = tl.where(k0, 0, tl.where(k1, 1, 2))
    second = tl.where(k3, a3, tl.where(k2, a2, a1))
    i1 = tl.where(k3, 3, tl.where(k2, 2, 1))
    return first, second, i0 | (i1 << 2)


@triton.jit
def sp24_rows_kernel(x_ptr, v_ptr, m_ptr, e_ptr, K, BM: tl.constexpr):
    """x [M, K] bf16 -> v int32 [M, K/8] (4 e4m3 bytes = 2 kept pairs), m uint8 [M, K/8] (2 nibbles), e [M, K/64]."""
    pm, pk = tl.program_id(0), tl.program_id(1)
    rm = (pm * BM + tl.arange(0, BM)).to(tl.int64)
    p = tl.arange(0, 8)
    base = x_ptr + rm[:, None] * K + pk * 64 + 8 * p[None, :]
    x0 = tl.load(base + 0).to(tl.float32)
    x1 = tl.load(base + 1).to(tl.float32)
    x2 = tl.load(base + 2).to(tl.float32)
    x3 = tl.load(base + 3).to(tl.float32)
    x4 = tl.load(base + 4).to(tl.float32)
    x5 = tl.load(base + 5).to(tl.float32)
    x6 = tl.load(base + 6).to(tl.float32)
    x7 = tl.load(base + 7).to(tl.float32)
    k0, k1, k2, k3 = _top2(x0, x1, x2, x3)
    k4, k5, k6, k7 = _top2(x4, x5, x6, x7)
    fe, se, ne = _compress4(x0, x1, x2, x3, k0, k1, k2, k3)
    fo, so, no = _compress4(x4, x5, x6, x7, k4, k5, k6, k7)
    amax = tl.max(tl.maximum(tl.maximum(tl.abs(fe), tl.abs(se)), tl.maximum(tl.abs(fo), tl.abs(so))), axis=1)
    e = _exponent(amax)
    sc = _scale_of(e)[:, None]
    word = _q8(fe, sc) | (_q8(se, sc) << 8) | (_q8(fo, sc) << 16) | (_q8(so, sc) << 24)
    out = rm[:, None] * (K // 8) + pk * 8 + p[None, :]
    tl.store(v_ptr + out, word)
    tl.store(m_ptr + out, (ne | (no << 4)).to(tl.uint8))
    tl.store(e_ptr + rm * (K // 64) + pk, e.to(tl.uint8))

@triton.jit
def _split8(x, BM: tl.constexpr):
    """[BM, 64] -> eight [BM, 8] tensors; tensor p holds element p of each 8-element chunk."""
    y = tl.reshape(x, (BM, 8, 2, 2, 2))
    lo, hi = tl.split(y)  # last dim = bit0
    l0, l1 = tl.split(lo)  # bit1
    h0, h1 = tl.split(hi)
    e0, e4 = tl.split(l0)  # bit2
    e2, e6 = tl.split(l1)
    e1, e5 = tl.split(h0)
    e3, e7 = tl.split(h1)
    return e0, e1, e2, e3, e4, e5, e6, e7


@triton.jit
def sp24_rows_v3_kernel(x_ptr, v_ptr, m_ptr, e_ptr, K, BM: tl.constexpr):
    pm, pk = tl.program_id(0), tl.program_id(1)
    rm = (pm * BM + tl.arange(0, BM)).to(tl.int64)
    cols = pk * 64 + tl.arange(0, 64)
    x = tl.load(x_ptr + rm[:, None] * K + cols[None, :]).to(tl.float32)
    x0, x1, x2, x3, x4, x5, x6, x7 = _split8(x, BM)
    k0, k1, k2, k3 = _top2(x0, x1, x2, x3)
    k4, k5, k6, k7 = _top2(x4, x5, x6, x7)
    fe, se, ne = _compress4(x0, x1, x2, x3, k0, k1, k2, k3)
    fo, so, no = _compress4(x4, x5, x6, x7, k4, k5, k6, k7)
    amax = tl.max(tl.maximum(tl.maximum(tl.abs(fe), tl.abs(se)), tl.maximum(tl.abs(fo), tl.abs(so))), axis=1)
    e = _exponent(amax)
    sc = _scale_of(e)[:, None]
    word = _q8(fe, sc) | (_q8(se, sc) << 8) | (_q8(fo, sc) << 16) | (_q8(so, sc) << 24)
    p = tl.arange(0, 8)
    out = rm[:, None] * (K // 8) + pk * 8 + p[None, :]
    tl.store(v_ptr + out, word)
    tl.store(m_ptr + out, (ne | (no << 4)).to(tl.uint8))
    tl.store(e_ptr + rm * (K // 64) + pk, e.to(tl.uint8))
'''


def gen_sp24t(name="sp24t_kernel", contiguous=False) -> str:
    L = []
    w = L.append
    w("@triton.jit")
    w(f"def {name}(x_ptr, rv_ptr, rmeta_ptr, re_ptr, cv_ptr, cmeta_ptr, ce_ptr, K):")
    w('    """64x64 tile. rv int16 [M, K/4] (kept pair per row-group), rmeta uint8 [M, K/4], re [M, K/64];')
    w('    cv uint8 [M/2, K] (kept pair per column-group, along M), cmeta uint8 [M/4, K], ce [M/64, K]."""')
    w("    pm, pk = tl.program_id(0), tl.program_id(1)")
    w("    ii = tl.arange(0, 16)[:, None]")
    w("    jj = tl.arange(0, 16)[None, :]")
    w("    row0 = (pm * 64).to(tl.int64)")
    if not contiguous:
        w("    base = x_ptr + (row0 + 4 * ii) * K + pk * 64 + 4 * jj")
    if contiguous:
        w("    cols = pk * 64 + tl.arange(0, 64)[None, :]")
        for r in range(4):
            w(f"    y = tl.reshape(tl.load(x_ptr + (row0 + 4 * ii + {r}) * K + cols).to(tl.float32), (16, 16, 2, 2))")
            w("    lo, hi = tl.split(y)")
            w(f"    x{r}0, x{r}2 = tl.split(lo)")
            w(f"    x{r}1, x{r}3 = tl.split(hi)")
        for r in range(4):
            for c in range(4):
                w(f"    a{r}{c} = tl.abs(x{r}{c})")
    else:
        for r in range(4):
            for c in range(4):
                w(f"    x{r}{c} = tl.load(base + {r} * K + {c}).to(tl.float32)")
                w(f"    a{r}{c} = tl.abs(x{r}{c})")
    for r in range(4):
        for pi, (a, b) in enumerate(PAIRS):
            w(f"    s{r}_{pi} = a{r}{a} + a{r}{b}")

    def half(rows, tag):
        buckets = {}
        for p0, p1 in itertools.product(range(6), repeat=2):
            cnt = [0] * 4
            for p in (p0, p1):
                for col in PAIRS[p]:
                    cnt[col] += 1
            buckets.setdefault(tuple(cnt), []).append((p0, p1))
        names = {}
        for bi, (cnt, combos) in enumerate(sorted(buckets.items())):
            bv, ba = f"{tag}v{bi}", f"{tag}a{bi}"
            for k, (p0, p1) in enumerate(combos):
                val = f"s{rows[0]}_{p0} + s{rows[1]}_{p1}"
                code = p0 * 6 + p1
                if k == 0:
                    w(f"    {bv} = {val}")
                    w(f"    {ba} = tl.full(({16}, {16}), {code}, tl.int32)")
                else:
                    w(f"    t = {val}")
                    w(f"    u = t > {bv}")
                    w(f"    {bv} = tl.where(u, t, {bv})")
                    w(f"    {ba} = tl.where(u, {code}, {ba})")
            names[cnt] = (bv, ba)
        return names

    top = half((0, 1), "T")
    bot = half((2, 3), "B")
    first = True
    for cnt, (tv, ta) in top.items():
        need = tuple(2 - x for x in cnt)
        if need not in bot:
            continue
        bv, ba = bot[need]
        if first:
            w(f"    best = {tv} + {bv}")
            w(f"    btop = {ta}")
            w(f"    bbot = {ba}")
            first = False
        else:
            w(f"    t = {tv} + {bv}")
            w("    u = t > best")
            w("    best = tl.where(u, t, best)")
            w(f"    btop = tl.where(u, {ta}, btop)")
            w(f"    bbot = tl.where(u, {ba}, bbot)")
    w("    q0 = btop // 6")
    w("    q1 = btop % 6")
    w("    q2 = bbot // 6")
    w("    q3 = bbot % 6")
    for r in range(4):
        for c in range(4):
            members = [pi for pi, pr in enumerate(PAIRS) if c in pr]
            cond = " | ".join(f"(q{r} == {pi})" for pi in members)
            w(f"    k{r}{c} = {cond}")
    # rows: 2:4 along K
    for r in range(4):
        w(f"    f, s, nib = _compress4(x{r}0, x{r}1, x{r}2, x{r}3, k{r}0, k{r}1, k{r}2, k{r}3)")
        w("    e = _exponent(tl.max(tl.maximum(tl.abs(f), tl.abs(s)), axis=1))")
        w("    sc = _scale_of(e)[:, None]")
        w(f"    rr = row0 + 4 * ii + {r}")
        w("    out = rr * (K // 4) + pk * 16 + jj")
        w("    tl.store(rv_ptr + out, (_q8(f, sc) | (_q8(s, sc) << 8)).to(tl.int16))")
        w("    tl.store(rmeta_ptr + out, nib.to(tl.uint8))")
        w(f"    tl.store(re_ptr + (row0 + 4 * tl.arange(0, 16) + {r}) * (K // 64) + pk, e.to(tl.uint8))")
    # cols: 2:4 along M
    for c in range(4):
        w(f"    f, s, nib = _compress4(x0{c}, x1{c}, x2{c}, x3{c}, k0{c}, k1{c}, k2{c}, k3{c})")
        w("    e = _exponent(tl.max(tl.maximum(tl.abs(f), tl.abs(s)), axis=0))")
        w("    sc = _scale_of(e)[None, :]")
        w(f"    cc = pk * 64 + 4 * jj + {c}")
        w("    crow = (pm * 32).to(tl.int64) + 2 * ii")
        w("    tl.store(cv_ptr + crow * K + cc, _q8(f, sc).to(tl.uint8))")
        w("    tl.store(cv_ptr + (crow + 1) * K + cc, _q8(s, sc).to(tl.uint8))")
        w("    tl.store(cmeta_ptr + ((pm * 16).to(tl.int64) + ii) * K + cc, nib.to(tl.uint8))")
        w(f"    tl.store(ce_ptr + pm.to(tl.int64) * K + pk * 64 + 4 * tl.arange(0, 16) + {c}, e.to(tl.uint8))")
    return "\n".join(L) + "\n"


WRAPPERS = """

def sp24_rows(x, BM=64, num_warps=4, kernel=None):
    kernel = kernel or sp24_rows_kernel

    M, K = x.shape
    v = torch.empty(M, K // 8, device=x.device, dtype=torch.int32)
    m = torch.empty(M, K // 8, device=x.device, dtype=torch.uint8)
    e = torch.empty(M, K // 64, device=x.device, dtype=torch.uint8)
    kernel[(M // BM, K // 64)](x, v, m, e, K, BM=BM, num_warps=num_warps)
    return v.view(torch.uint8).view(torch.float8_e4m3fn), m, e


def sp24t(x, num_warps=4, kernel=None):
    kernel = kernel or sp24t_kernel

    M, K = x.shape
    rv = torch.empty(M, K // 4, device=x.device, dtype=torch.int16)
    rmeta = torch.empty(M, K // 4, device=x.device, dtype=torch.uint8)
    re = torch.empty(M, K // 64, device=x.device, dtype=torch.uint8)
    cv = torch.empty(M // 2, K, device=x.device, dtype=torch.uint8)
    cmeta = torch.empty(M // 4, K, device=x.device, dtype=torch.uint8)
    ce = torch.empty(M // 64, K, device=x.device, dtype=torch.uint8)
    kernel[(M // 64, K // 64)](x, rv, rmeta, re, cv, cmeta, ce, K, num_warps=num_warps)
    return (rv.view(torch.uint8).view(torch.float8_e4m3fn), rmeta, re), (cv.view(torch.float8_e4m3fn), cmeta, ce)
"""


def main():
    src = HEADER + "\n\n" + gen_sp24t() + "\n\n" + gen_sp24t("sp24t_v3_kernel", contiguous=True) + WRAPPERS
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "sp24_v2.py"), "w") as f:
        f.write(src)


if __name__ == "__main__":
    main()
