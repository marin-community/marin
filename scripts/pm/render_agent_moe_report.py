"""Render and audit the durable Agent MoE experiment digest.

The checked-in JSON Lines file is the source of truth. This script renders the
public Markdown report, verifies that the rendered file is current, and audits
the snapshot against the live GitHub tracker.

Usage:
    uv run scripts/pm/render_agent_moe_report.py
    uv run scripts/pm/render_agent_moe_report.py --check
    uv run scripts/pm/render_agent_moe_report.py --audit-github
    uv run scripts/pm/render_agent_moe_report.py --audit-github --json
"""

import argparse
import json
import subprocess
from collections import Counter
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_DATA_PATH = REPO_ROOT / "docs/reports/data/agent-moe-experiments.jsonl"
DEFAULT_REPORT_PATH = REPO_ROOT / "docs/reports/agent-moe-experiments.md"
GENERATED_MARKER = "<!-- Generated by scripts/pm/render_agent_moe_report.py. Do not edit by hand. -->"


class Outcome(StrEnum):
    WORKED = "Worked"
    PROMISING = "Promising"
    MIXED = "Mixed"
    DID_NOT_WORK = "Did not work"
    NOT_EVALUATED = "Not evaluated"
    IN_PROGRESS = "In progress"


OUTCOME_DESCRIPTIONS = {
    Outcome.WORKED: "Met the recorded effective-speedup gate or the experiment's narrower success criterion.",
    Outcome.PROMISING: "Positive evidence, but missing a larger-scale anchor or clean isolation.",
    Outcome.MIXED: "The answer changed by scale or metric, or a strict projection failed.",
    Outcome.DID_NOT_WORK: "A completed comparison showed no net benefit.",
    Outcome.NOT_EVALUATED: "No usable comparison was recorded, often because the work was superseded.",
    Outcome.IN_PROGRESS: "The issue remains active without a final verdict.",
}


@dataclass(frozen=True)
class Metadata:
    schema_version: int
    snapshot_date: str
    repository: str
    parent_issue: int
    title_prefix: str
    expected_issue_count: int
    headline_summary: str


@dataclass(frozen=True)
class Experiment:
    issue: int
    title: str
    category: str
    section: str | None
    outcome: Outcome
    model_flops_speedup: str
    wall_clock_speedup: str
    summary: str
    state: str
    source_updated_at: str


@dataclass(frozen=True)
class Foundation:
    issue: int
    title: str
    summary: str


@dataclass(frozen=True)
class ReportData:
    metadata: Metadata
    experiments: tuple[Experiment, ...]
    foundations: tuple[Foundation, ...]


@dataclass(frozen=True)
class RemoteIssue:
    number: int
    title: str
    state: str
    updated_at: str


@dataclass(frozen=True)
class AuditResult:
    new_issues: tuple[RemoteIssue, ...]
    removed_issue_numbers: tuple[int, ...]
    changed_issues: tuple[RemoteIssue, ...]

    @property
    def has_drift(self) -> bool:
        return bool(self.new_issues or self.removed_issue_numbers or self.changed_issues)


def _required(record: dict[str, Any], key: str) -> Any:
    value = record.get(key)
    if value is None:
        raise ValueError(f"record is missing required field {key!r}")
    return value


def load_report_data(path: Path) -> ReportData:
    """Load and validate the report's JSON Lines source."""
    records = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    metadata_records = [record for record in records if record.get("record_type") == "metadata"]
    if len(metadata_records) != 1:
        raise ValueError(f"expected one metadata record, found {len(metadata_records)}")

    raw_metadata = metadata_records[0]
    metadata = Metadata(
        schema_version=int(_required(raw_metadata, "schema_version")),
        snapshot_date=str(_required(raw_metadata, "snapshot_date")),
        repository=str(_required(raw_metadata, "repository")),
        parent_issue=int(_required(raw_metadata, "parent_issue")),
        title_prefix=str(_required(raw_metadata, "title_prefix")),
        expected_issue_count=int(_required(raw_metadata, "expected_issue_count")),
        headline_summary=str(_required(raw_metadata, "headline_summary")),
    )
    if metadata.schema_version != 1:
        raise ValueError(f"unsupported schema_version {metadata.schema_version}")

    experiments = tuple(
        Experiment(
            issue=int(_required(record, "issue")),
            title=str(_required(record, "title")),
            category=str(_required(record, "category")),
            section=None if record.get("section") is None else str(record["section"]),
            outcome=Outcome(_required(record, "outcome")),
            model_flops_speedup=str(_required(record, "model_flops_speedup")),
            wall_clock_speedup=str(_required(record, "wall_clock_speedup")),
            summary=str(_required(record, "summary")),
            state=str(_required(record, "state")),
            source_updated_at=str(_required(record, "source_updated_at")),
        )
        for record in records
        if record.get("record_type") == "experiment"
    )
    foundations = tuple(
        Foundation(
            issue=int(_required(record, "issue")),
            title=str(_required(record, "title")),
            summary=str(_required(record, "summary")),
        )
        for record in records
        if record.get("record_type") == "foundation"
    )

    issue_counts = Counter(experiment.issue for experiment in experiments)
    duplicates = sorted(issue for issue, count in issue_counts.items() if count > 1)
    if duplicates:
        raise ValueError(f"duplicate experiment issue numbers: {duplicates}")
    if len(experiments) != metadata.expected_issue_count:
        raise ValueError(f"expected {metadata.expected_issue_count} experiments, found {len(experiments)}")
    return ReportData(metadata=metadata, experiments=experiments, foundations=foundations)


def _table_text(value: str) -> str:
    return value.replace("|", r"\|").replace("\n", " ")


def _experiment_table(experiments: list[Experiment], repository: str) -> list[str]:
    lines = [
        "| Experiment | Outcome | Model-FLOPs speedup | Wall-clock speedup | TL;DR |",
        "|---|---|---:|---:|---|",
    ]
    for experiment in experiments:
        issue_url = f"https://github.com/{repository}/issues/{experiment.issue}"
        lines.append(
            f"| [#{experiment.issue} {_table_text(experiment.title)}]({issue_url}) "
            f"| {experiment.outcome.value} | {_table_text(experiment.model_flops_speedup)} "
            f"| {_table_text(experiment.wall_clock_speedup)} "
            f"| {_table_text(experiment.summary)} |"
        )
    return lines


def render_report(data: ReportData) -> str:
    """Render the public Markdown report from structured records."""
    metadata = data.metadata
    lines = [
        GENERATED_MARKER,
        "",
        "# Agent MoE experiment digest",
        "",
        "Agent MoE is a small-scale screen for modeling and training ideas in the Grug",
        "MoE setup. Each experiment compares a variant with a fixed baseline at one or",
        "more compute-optimal scales, then combines quality and throughput into an",
        "effective wall-clock speedup. Variants that survive the small-scale gate can be",
        "tested at larger scales and projected with a scaling-law fit.",
        "",
        f"This page summarizes the {metadata.expected_issue_count} `{metadata.title_prefix}` sub-issues attached to",
        f"[the April MoE tracker](https://github.com/{metadata.repository}/issues/{metadata.parent_issue})",
        f"as of {metadata.snapshot_date}. The",
        f"[Agent MoE playbook](https://github.com/{metadata.repository}/blob/main/experiments/grug/moe/agent.md)",
        f"and [baseline table](https://github.com/{metadata.repository}/blob/main/experiments/grug/moe/README.md)",
        "define the gates and reference runs. The",
        "[machine-readable snapshot](./data/agent-moe-experiments.jsonl) records the",
        "editorial outcome, issue state, and reviewed GitHub timestamp for each row.",
        "",
        "Model-FLOPs speedup is the loss-only equivalent-compute gain from the scaling-law",
        "inversion. Wall-clock speedup multiplies that gain by the measured throughput",
        "ratio. `≈` marks a value reconstructed from reported loss and throughput rather",
        "than copied from an issue table; `—` means the issue does not support the split.",
        "",
        "## TL;DR",
        "",
        metadata.headline_summary,
        "",
        "| Outcome | Count | Meaning |",
        "|---|---:|---|",
    ]
    outcome_counts = Counter(experiment.outcome for experiment in data.experiments)
    for outcome in Outcome:
        lines.append(f"| {outcome.value} | {outcome_counts[outcome]} | {OUTCOME_DESCRIPTIONS[outcome]} |")
    lines.extend(
        [
            "",
            "Issue state is not used as an outcome: several closed issues contain positive",
            "results, and several open issues already have useful measurements.",
            "",
        ]
    )

    category_order = list(dict.fromkeys(experiment.category for experiment in data.experiments))
    for category in category_order:
        lines.extend([f"## {category}", ""])
        category_experiments = [experiment for experiment in data.experiments if experiment.category == category]
        section_order = list(dict.fromkeys(experiment.section for experiment in category_experiments))
        for section in section_order:
            section_experiments = [experiment for experiment in category_experiments if experiment.section == section]
            if section is not None:
                lines.extend([f"### {section}", ""])
            lines.extend(_experiment_table(section_experiments, metadata.repository))
            lines.append("")

    lines.extend(
        [
            "## Related foundations outside the tracker",
            "",
            "These directly referenced Agent MoE issues were not attached as sub-issues of",
            f"[#{metadata.parent_issue}](https://github.com/{metadata.repository}/issues/{metadata.parent_issue}):",
            "",
        ]
    )
    for foundation in data.foundations:
        issue_url = f"https://github.com/{metadata.repository}/issues/{foundation.issue}"
        lines.append(f"- [#{foundation.issue} {foundation.title}]({issue_url}) {foundation.summary}")
    lines.extend(
        [
            "",
            f"The repository contains additional `{metadata.title_prefix}` issues outside",
            f"#{metadata.parent_issue}. They are not included here so the digest has one explicit, reproducible",
            "scope.",
            "",
        ]
    )
    return "\n".join(lines)


def audit_snapshot(data: ReportData, remote_issues: tuple[RemoteIssue, ...]) -> AuditResult:
    """Compare a local editorial snapshot with live tracker metadata."""
    local_by_number = {experiment.issue: experiment for experiment in data.experiments}
    remote_in_scope = {
        issue.number: issue for issue in remote_issues if issue.title.startswith(data.metadata.title_prefix)
    }
    new_issues = tuple(remote_in_scope[number] for number in sorted(remote_in_scope.keys() - local_by_number.keys()))
    removed_issue_numbers = tuple(sorted(local_by_number.keys() - remote_in_scope.keys()))
    changed_issues = tuple(
        remote_in_scope[number]
        for number in sorted(local_by_number.keys() & remote_in_scope.keys())
        if remote_in_scope[number].updated_at != local_by_number[number].source_updated_at
        or remote_in_scope[number].state != local_by_number[number].state
    )
    return AuditResult(
        new_issues=new_issues,
        removed_issue_numbers=removed_issue_numbers,
        changed_issues=changed_issues,
    )


def fetch_tracker_issues(metadata: Metadata) -> tuple[RemoteIssue, ...]:
    """Fetch all sub-issues from the configured tracker."""
    owner, name = metadata.repository.split("/", maxsplit=1)
    query = """
query($owner: String!, $name: String!, $number: Int!, $cursor: String) {
  repository(owner: $owner, name: $name) {
    issue(number: $number) {
      subIssues(first: 100, after: $cursor) {
        nodes { number title state updatedAt }
        pageInfo { hasNextPage endCursor }
      }
    }
  }
}
"""
    cursor: str | None = None
    issues: list[RemoteIssue] = []
    while True:
        command = [
            "gh",
            "api",
            "graphql",
            "-f",
            f"query={query}",
            "-F",
            f"owner={owner}",
            "-F",
            f"name={name}",
            "-F",
            f"number={metadata.parent_issue}",
        ]
        if cursor is not None:
            command.extend(["-f", f"cursor={cursor}"])
        result = subprocess.run(command, check=True, capture_output=True, text=True)
        payload = json.loads(result.stdout)
        sub_issues = payload["data"]["repository"]["issue"]["subIssues"]
        issues.extend(
            RemoteIssue(
                number=int(node["number"]),
                title=str(node["title"]),
                state=str(node["state"]),
                updated_at=str(node["updatedAt"]),
            )
            for node in sub_issues["nodes"]
        )
        if not sub_issues["pageInfo"]["hasNextPage"]:
            return tuple(issues)
        cursor = str(sub_issues["pageInfo"]["endCursor"])


def _print_audit(result: AuditResult) -> None:
    if not result.has_drift:
        print("Agent MoE GitHub audit: no drift")
        return
    if result.new_issues:
        print("New tracker issues requiring summaries:")
        for issue in result.new_issues:
            print(f"  #{issue.number} {issue.title}")
    if result.removed_issue_numbers:
        print("Issues no longer attached to the tracker:")
        for number in result.removed_issue_numbers:
            print(f"  #{number}")
    if result.changed_issues:
        print("Issues updated since their recorded snapshot:")
        for issue in result.changed_issues:
            print(f"  #{issue.number} {issue.state} updated {issue.updated_at}")


def _audit_json(result: AuditResult) -> str:
    return json.dumps(
        {
            "has_drift": result.has_drift,
            "new_issues": [
                {
                    "number": issue.number,
                    "title": issue.title,
                    "state": issue.state,
                    "updated_at": issue.updated_at,
                }
                for issue in result.new_issues
            ],
            "removed_issue_numbers": list(result.removed_issue_numbers),
            "changed_issues": [
                {
                    "number": issue.number,
                    "title": issue.title,
                    "state": issue.state,
                    "updated_at": issue.updated_at,
                }
                for issue in result.changed_issues
            ],
        },
        sort_keys=True,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA_PATH)
    parser.add_argument("--output", type=Path, default=DEFAULT_REPORT_PATH)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--audit-github", action="store_true")
    parser.add_argument("--json", action="store_true", help="Emit the GitHub audit as JSON")
    args = parser.parse_args()
    if args.json and not args.audit_github:
        parser.error("--json requires --audit-github")

    data = load_report_data(args.data)
    if args.audit_github:
        result = audit_snapshot(data, fetch_tracker_issues(data.metadata))
        if args.json:
            print(_audit_json(result))
        else:
            _print_audit(result)
        raise SystemExit(1 if result.has_drift else 0)

    rendered = render_report(data)
    if args.check:
        if not args.output.exists() or args.output.read_text() != rendered:
            raise SystemExit(f"{args.output} is stale; run {Path(__file__).relative_to(REPO_ROOT)}")
        print(f"Agent MoE report is current: {args.output}")
        return
    args.output.write_text(rendered)
    print(f"Rendered {len(data.experiments)} Agent MoE experiments to {args.output}")


if __name__ == "__main__":
    main()
