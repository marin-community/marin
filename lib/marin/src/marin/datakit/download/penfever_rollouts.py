def outcome_tag(verifier_output: str | None, result: str | None) -> str | None:
    """Map verifier or result metadata to the shared trajectory outcome tags."""
    if result:
        try:
            return TRAJECTORY_SOLVED_TAG if float(result.strip()) >= 1.0 else TRAJECTORY_FAILED_TAG
        except ValueError:
            return TRAJECTORY_UNVERIFIED_TAG
    if not verifier_output:
        return None
    upper = verifier_output.upper()
    if "VERIFIER: PASS" in upper or "ALL TESTS PASSED" in upper:
        return TRAJECTORY_SOLVED_TAG
    if "VERIFIER: FAIL" in upper or "FAILED" in upper:
        return TRAJECTORY_FAILED_TAG
    return None


def row_to_doc(dataset: PenfeverRollout) -> Callable[[dict], list[dict]]:
    """Build a row-to-document transform for one repository."""
    counter_prefix = f"penfever_rollouts/{dataset.cohort_name}/{dataset.task_source}"

    def transform_row(row: dict) -> list[dict]:
        conversations = row.get("conversations")
        if not conversations:
            counters.pipeline.update_counter(f"{counter_prefix}/dropped", 1)
            return []

        tag = outcome_tag(row.get("verifier_output"), row.get("result"))
        rendered = "\n\n".join(render_role_message(message) for message in conversations)
        text = f"{tag}\n\n{rendered}" if tag else rendered

        counters.pipeline.update_counter(f"{counter_prefix}/kept", 1)
        return [
            {
                **text_document(text, dataset.hf_dataset_id),
                "teacher": dataset.teacher,
                "task_source": dataset.task_source,
            }
        ]

    return transform_row


def transform(dataset: PenfeverRollout, input_path: str, output_path: str) -> None:
    pipeline = (
        Dataset.from_files(f"{input_path.rstrip('/')}/**/*.parquet")
        .flat_map(load_parquet_batched)
        .flat_map(row_to_doc(dataset))
        .write_parquet(
            f"{output_path.rstrip('/')}/data-{{shard:05d}}-of-{{total:05d}}.parquet",
            skip_existing=True,
        )
    )
    ctx = ZephyrContext(
        name=f"penfever-{dataset.cohort_name}-{dataset.task_source}-transform",
        resources=ResourceConfig(cpu=1, ram="32g"),
    )
    ctx.execute(pipeline)


def _rollout_steps(dataset: PenfeverRollout) -> tuple[StepSpec, StepSpec]:
    download = download_hf_step(
        f"raw/{dataset.marin_name}",
        hf_dataset_id=dataset.hf_dataset_id,
        revision=dataset.revision,
    )
    processed = StepSpec(
        name=f"processed/{dataset.marin_name}",
        deps=[download],
        fn=lambda output_path, _dataset=dataset, _download=download: transform(
            dataset=_dataset,
            input_path=_download.output_path,
            output_path=output_path,
        ),
        hash_attrs={
            "version": "v2",
            "teacher": dataset.teacher,
            "task_source": dataset.task_source,
        },
    )
    normalized = normalize_step(name=f"normalized/{dataset.marin_name}", download=processed)
    return processed, normalized


def penfever_rollouts_normalize_steps() -> dict[str, tuple[StepSpec, ...]]:
    """Return the transform and normalize chain for every Penfever dataset."""
    return {dataset.marin_name: _rollout_steps(dataset) for dataset in PENFEVER_ROLLOUTS}
