"""Public Penfever agentic rollout datasets.

The four cohorts were generated by the OT-Agent datagen pipeline. Every dataset
uses the same ``conversations``, ``result``, and ``verifier_output`` schema, so
one transform renders all 142 repositories as role-tagged documents with
outcome and provenance metadata.
"""

