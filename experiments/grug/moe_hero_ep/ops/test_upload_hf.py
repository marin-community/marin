BASE_REVISION = "a" * 40


class FakeHub:
    """Immutable commit snapshots at the external Hub boundary."""

    def __init__(self, baseline: dict[str, bytes]):
        self.snapshots: dict[str, dict[str, bytes]] = {BASE_REVISION: baseline}
        self.branches: dict[str, str] = {}
        self.uploads = []
        self.fail_filename = None
        self.token = "test-token"

    def model_info(self, repo_id):
        return SimpleNamespace(private=True)

    def create_branch(self, repo_id, *, branch, revision, **kwargs):
        if branch not in self.branches:
            self.branches[branch] = revision

    def files(self, revision):
        return self.snapshots[self.branches.get(revision, revision)]

    def _commit(self, branch, additions):
        contents = {**self.files(branch), **additions}
        oid = f"{len(self.snapshots):040x}"
        self.snapshots[oid] = contents
        self.branches[branch] = oid
        return SimpleNamespace(oid=oid)

    def upload_file(self, *, revision, path_in_repo, path_or_fileobj, **kwargs):
        if path_in_repo == self.fail_filename:
            raise ConnectionError("Interrupted external upload")
        data = path_or_fileobj if isinstance(path_or_fileobj, bytes) else Path(path_or_fileobj).read_bytes()
        self.uploads.append(path_in_repo)
        return self._commit(revision, {path_in_repo: data})

    def create_commit(self, *, revision, operations, **kwargs):
        return self._commit(
            revision,
            {
                op.path_in_repo: (
                    op.path_or_fileobj
                    if isinstance(op.path_or_fileobj, bytes)
                    else Path(op.path_or_fileobj).read_bytes()
                )
                for op in operations
            },
        )

    def list_repo_tree(self, repo_id, *, revision, **kwargs):
        return [
            RepoFile(
                path=name,
                size=len(data),
                oid="0" * 40,
                lfs=(
                    {"size": len(data), "oid": hashlib.sha256(data).hexdigest(), "pointerSize": 128}
                    if name.endswith(".safetensors")
                    else None
                ),
            )
            for name, data in self.files(revision).items()
        ]

    def get_paths_info(self, repo_id, *, paths, revision, **kwargs):
        return [item for item in self.list_repo_tree(repo_id, revision=revision) if item.path in paths]


