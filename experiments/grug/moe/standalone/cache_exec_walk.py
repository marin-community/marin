"""MXFP8-011: schema-less protobuf walk of serialized jit_train_step cache entries.

Walks the protobuf wire format of a decompressed JAX persistent-cache
executable, recursively descending into length-delimited fields, and reports
every field above a size threshold with a content sniff (ELF header with
machine/e_flags, PTX text, nested-zstd, printable-string sample). Used to
locate the GPU binary the CUDA driver rejects in the cute-producer load
failure and to diff failing (cute) vs passing (xla) executables.

Also extracts the largest CUDA ELF blobs to local files (--extract DIR) so a
follow-up GPU job can feed them to cuModuleLoadData in isolation.
"""

import pathlib
import sys

import fsspec

from experiments.grug.moe.standalone.cache_exec_carve import decompress

ELF_MAGIC = b"\x7fELF"
EM_CUDA = 190
MIN_REPORT = 20_000


def _read_varint(buf: bytes, pos: int) -> tuple[int, int] | None:
    result = 0
    shift = 0
    start = pos
    while pos < len(buf) and shift <= 63:
        b = buf[pos]
        result |= (b & 0x7F) << shift
        pos += 1
        if not b & 0x80:
            return result, pos
        shift += 7
    del start
    return None


def _parse_fields(buf: bytes, base: int, end: int) -> list[tuple[int, int, int, int]] | None:
    """Parse one message level; returns [(field_no, wire_type, payload_off, payload_len)]."""
    fields = []
    pos = base
    while pos < end:
        r = _read_varint(buf, pos)
        if r is None:
            return None
        tag, pos = r
        field_no, wt = tag >> 3, tag & 7
        if field_no == 0 or field_no > 10_000:
            return None
        if wt == 0:
            r = _read_varint(buf, pos)
            if r is None:
                return None
            _, pos = r
            fields.append((field_no, wt, pos, 0))
        elif wt == 1:
            if pos + 8 > end:
                return None
            fields.append((field_no, wt, pos, 8))
            pos += 8
        elif wt == 5:
            if pos + 4 > end:
                return None
            fields.append((field_no, wt, pos, 4))
            pos += 4
        elif wt == 2:
            r = _read_varint(buf, pos)
            if r is None:
                return None
            ln, pos = r
            if pos + ln > end:
                return None
            fields.append((field_no, wt, pos, ln))
            pos += ln
        else:
            return None
    return fields if pos == end else None


def _sniff(payload: bytes) -> str:
    if payload[:4] == ELF_MAGIC:
        import struct  # noqa: PLC0415

        (machine,) = struct.unpack_from("<H", payload, 18)
        (flags,) = struct.unpack_from("<I", payload, 48)
        return f"ELF machine={machine} flags={hex(flags)}"
    if payload[:4] == b"\x28\xb5\x2f\xfd":
        return "zstd"
    if b".visible .entry" in payload[:4096] or payload[:32].startswith(b"//\n// Generated by NVIDIA"):
        return "PTX"
    sample = payload[:60]
    if all(32 <= c < 127 or c in (9, 10, 13) for c in sample):
        return f"text {sample.decode(errors='replace')!r}"
    return f"bin {payload[:12].hex()}"


def walk(buf: bytes, base: int, end: int, path: str, out: list, depth: int = 0) -> None:
    fields = _parse_fields(buf, base, end)
    if fields is None:
        return
    for field_no, wt, off, ln in fields:
        if wt != 2:
            continue
        p = f"{path}.{field_no}"
        payload = buf[off : off + ln]
        if ln >= MIN_REPORT:
            out.append((p, off, ln, _sniff(payload)))
        if depth < 12 and ln > 0 and payload[:4] != ELF_MAGIC:
            walk(buf, off, off + ln, p, out, depth + 1)


def analyze_entry(path: str, extract_dir: str | None) -> None:
    with fsspec.open(path, "rb") as f:
        raw = f.read()
    buf = decompress(raw)
    print(f"ENTRY {path}")
    print(f"  raw={len(raw)} decompressed={len(buf)} head={buf[:16].hex()}")
    # jax cache entries prefix the serialized executable with a 4-byte
    # big-endian compile time (compilation_cache.combine_executable_and_time).
    out: list = []
    for start in (4, 0, *range(1, 64)):
        if _parse_fields(buf, start, len(buf)) is not None:
            print(f"  proto_start_offset={start}")
            walk(buf, start, len(buf), "", out)
            break
    else:
        print("  NO VALID PROTO PARSE at offsets 0..63")
    seen_offsets = set()
    big = []
    for p, off, ln, sniff in sorted(out, key=lambda t: -t[2]):
        # skip fields fully contained in an already-reported bigger field at
        # the same offset (message wrappers around one big bytes field)
        if off in seen_offsets:
            continue
        seen_offsets.add(off)
        big.append((p, off, ln, sniff))
    for p, off, ln, sniff in big[:40]:
        print(f"  field {p} off={off} len={ln} :: {sniff}")
    if extract_dir:
        d = pathlib.Path(extract_dir)
        d.mkdir(parents=True, exist_ok=True)
        n = 0
        for p, off, ln, sniff in big:
            if sniff.startswith("ELF") or sniff == "PTX":
                kind = "elf" if sniff.startswith("ELF") else "ptx"
                fp = d / f"{pathlib.Path(path).name[:40]}-{off}.{kind}"
                fp.write_bytes(buf[off : off + ln])
                print(f"  extracted {fp} ({ln} bytes, {sniff})")
                n += 1
                if n >= 8:
                    break


def main() -> None:
    extract_dir = None
    args = []
    it = iter(sys.argv[1:])
    for a in it:
        if a == "--extract":
            extract_dir = next(it)
        else:
            args.append(a)
    for path in args:
        analyze_entry(path, extract_dir)
        print()


if __name__ == "__main__":
    main()
