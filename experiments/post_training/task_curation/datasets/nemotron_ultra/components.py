def pipeline_name(blend: str, path: str) -> str:
    return NAME_PREFIX + blend + "_" + re.sub(r"[^a-z0-9]+", "_", path.lower()).strip("_")


def _source(blend: str, path: str) -> RlDataSource[CurationRecipe]:
    component = COMPONENTS[path]
    name, _, split = path.partition("/")
    select = SweRows(name, SweSplit(split)) if split else ComponentRows(name)
    inputs = {SWE_GYM.repo: SWE_GYM} if split else dict(component.inputs)
    return RlDataSource(
        pipeline=process_rows,
        info=replace(BLENDS[blend][path], task_format=TaskFormat.MARINSKYRL),
        config=CurationRecipe(
            name=pipeline_name(blend, path),
            source=HfSource(
                ULTRA_REPO,
                ULTRA_REVISION,
                (f"{blend}.jsonl",),
                SourceFormat.JSONL,
                select=select,
                decode=component.decode,
                prepare=prepare_blend,
                prepared_component=name,
            ),
            convert=component.convert,
            version=RECIPE_VERSIONS.get(path, BASE_RECIPE_VERSION),
            intended_use=IntendedUse.TRAIN,
            rubric=component.rubric,
            controls=component.controls,
            inputs=inputs,
            grader=component.grader,
        ),
    )


def repaired_tau_source(blend: str) -> RlDataSource[PrebuiltCohort]:
    """Bind the repaired tau cohort; retain its conversion recipe only as lineage."""
    cohort = TAU_REPAIR_RELEASES[blend]
    return RlDataSource(
        pipeline=import_taskcompendium_prebuilt,
        config=cohort,
        info=replace(
            BLENDS[blend][TAU_PIVOT_COMPONENT],
            count=cohort.expected_rows,
            dataset=cohort.dataset,
            task_format=TaskFormat.TASKCOMPENDIUM,
            notes=TAU_REPAIR_NOTE,
        ),
    )


def sources() -> list[RlDataSource]:
    declared = []
    for blend, paths in BLENDS.items():
        for path in paths:
            if path == TAU_PIVOT_COMPONENT:
                declared.append(repaired_tau_source(blend))
            else:
                declared.append(_source(blend, path))
    return declared
