"""ProofNet-Verified fixture rows and the frozen contracts converted from them."""

import json
from pathlib import Path
from typing import Any

from taskcompendium.models import TaskSpec
from taskcompendium.runtime.resources import resource_bytes

from experiments.post_training.task_curation.datasets.lean.proofs import sources

PROOFNET = sources()[0].config
PROOFS_FIXTURE = Path(__file__).parent / "fixtures/lean/proofnet_proofs.json"
"""Rows copied from the pinned ProofNet-Verified payload, each with a proof checked by the grader's toolchain."""


def proofnet_row(**fields: Any) -> dict[str, Any]:
    """A ProofNet-Verified row shaped like the pinned payload, with ``fields`` replacing its values."""
    row = {
        "index": 1,
        "name": "Artin_exercise_2_2_9",
        "textbook": "Artin",
        "header": (
            "import Mathlib\n\nopen Function Fintype Subgroup Ideal Polynomial Submodule\nopen scoped BigOperators"
        ),
        "helper": "",
        "informal_stmt": "Let $H$ be the subgroup generated by two commuting elements. Prove that $H$ is abelian.",
        "formal_stmt": (
            "theorem Artin_exercise_2_2_9 {G : Type*} [Group G] {a b : G}\n  (h : a * b = b * a) :\n"
            "  ∀ x y : closure {a, b}, x * y = y * x := by\n  sorry"
        ),
        "informal_proof": "Since $a$ and $b$ commute, every product of powers of them commutes.",
        "formal_proof": "to avoid data contamination, the formal proof is in proofnet_verified_gt.zip",
    }
    return {**row, **fields}


def contract(task: TaskSpec) -> dict[str, str]:
    """The frozen contract a converted task ships to its grader."""
    config = next(item for item in task.resources.verifier if item.path == "config.json")
    return json.loads(resource_bytes(config))


def real_proofs() -> dict[str, tuple[dict[str, Any], str]]:
    """Each fixture row's theorem name, mapped to the row and its proof."""
    entries = json.loads(PROOFS_FIXTURE.read_text())
    return {entry["row"]["name"]: (entry["row"], entry["proof"]) for entry in entries}


REAL_PROOFS = real_proofs()
