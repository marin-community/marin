"""One-shot revalidation of a completed task checkpoint without construction repair."""

from __future__ import annotations

import hashlib
import json
import re
import shutil
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from .inference import atomic_json
from .synthesis import PROJECT_ROOT, SOURCE_LOCK, _handoff, _safe_name, load_accepted

SCHEMA = "capability-completed-checkpoint-revalidation-bundle-v1"
REQUEST_SCHEMA = "capability-completed-checkpoint-revalidation-request-v1"
PROVENANCE_SCHEMA = "capability-controller-provenance-v1"


class CheckpointRevalidationError(ValueError):
    """The purported completed checkpoint is incomplete or has changed."""


@dataclass(frozen=True)
class CheckpointRevalidationPlan:
    bundle: Path
    restore_seed: Path
    construction_root: Path
    item_name: str
    item: dict[str, Any]
    repair_rounds: tuple[int, ...]
    protected_workspace: tuple[tuple[str, str], ...]
    protected_sessions: tuple[tuple[str, str], ...]
    protected_repairs: tuple[tuple[str, str], ...]
    accepted_contract_sha256: str
    source_provenance: dict[str, str]
    request_sha256: str
    bundle_manifest_sha256: str


@dataclass(frozen=True)
class PreparedCheckpointRevalidation:
    plan: CheckpointRevalidationPlan
    root: Path
    item_root: Path
    history_root: Path
    operation_path: Path
    prior_status: dict[str, Any]


def _sha(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _read(path: Path) -> Any:
    if path.is_symlink() or not path.is_file():
        raise CheckpointRevalidationError(f"missing or linked checkpoint member: {path}")
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as error:
        raise CheckpointRevalidationError(f"unreadable checkpoint JSON: {path}") from error


def _digest(value: Any, label: str) -> str:
    if not isinstance(value, str) or re.fullmatch(r"[0-9a-f]{64}", value) is None:
        raise CheckpointRevalidationError(f"{label} is not a SHA-256 digest")
    return value


def _inventory(root: Path) -> dict[str, str]:
    if root.is_symlink() or not root.is_dir() or any(path.is_symlink() for path in root.rglob("*")):
        raise CheckpointRevalidationError("checkpoint tree is unavailable or linked")
    return {
        path.relative_to(root).as_posix(): _sha(path)
        for path in sorted(root.rglob("*")) if path.is_file()
    }


def _require_provenance(value: Any, label: str) -> dict[str, str]:
    required = {
        "source_tree_sha256",
        "synthesis_sha256",
        "taskcompendium_source_lock_sha256",
        "taskcompendium_overlay_lock_sha256",
    }
    if not isinstance(value, dict) or value.get("schema_version") != PROVENANCE_SCHEMA or set(value) != required | {"schema_version"}:
        raise CheckpointRevalidationError(f"{label} controller provenance is malformed")
    return {name: _digest(value[name], f"{label} {name}") for name in required}


def _source_inventory(package: Path) -> dict[str, str]:
    """Hash controller source, excluding import caches and generated bytecode."""
    return {
        path.relative_to(package).as_posix(): _sha(path)
        for path in sorted(package.rglob("*.py"))
        if "__pycache__" not in path.parts and path.is_file() and not path.is_symlink()
    }


def _verify_selective_snapshot(root: Path, item_name: str, construction_root: str,
                               metadata_root: Path | None = None) -> tuple[dict[str, str], dict[str, Any]]:
    """Verify every downloaded byte while keeping unrelated item omissions visible."""
    if root.is_symlink() or not root.is_dir():
        raise CheckpointRevalidationError("checkpoint source is unavailable or linked")
    metadata = metadata_root or root
    pull = _read(metadata / "pull-manifest.json")
    capture = _read(metadata / "snapshot-capture.json")
    raw = capture.get("remote_manifest_json") if isinstance(capture, dict) else None
    if not isinstance(raw, str) or hashlib.sha256(raw.encode()).hexdigest() != capture.get("remote_manifest_sha256"):
        raise CheckpointRevalidationError("captured remote manifest fingerprint mismatch")
    try:
        remote = json.loads(raw)
    except json.JSONDecodeError as error:
        raise CheckpointRevalidationError("captured remote manifest is invalid") from error
    files = remote.get("files") if isinstance(remote, dict) else None
    omitted = remote.get("omitted") if isinstance(remote, dict) else None
    if (not isinstance(pull, dict) or pull.get("schema_version") != "capability-snapshot-pull-v1"
            or not isinstance(files, dict) or not files or not isinstance(omitted, dict)
            or pull.get("files") != files or pull.get("omitted", {}) != omitted
            or pull.get("remote_manifest_sha256") != capture.get("remote_manifest_sha256")
            or pull.get("remote_snapshot_id") != remote.get("snapshot_id")
            or remote.get("final") is not True or pull.get("remote_final") is not True
            or pull.get("complete_manifest") is not True
            or type(pull.get("complete_snapshot")) is not bool):
        raise CheckpointRevalidationError("checkpoint is not a verified terminal snapshot")
    if not omitted and (pull["complete_manifest"] is not True or pull["complete_snapshot"] is not True):
        raise CheckpointRevalidationError("checkpoint has unrecorded incomplete source")
    if any(not isinstance(name, str) or not isinstance(reason, str) or not reason for name, reason in omitted.items()):
        raise CheckpointRevalidationError("checkpoint omission map is malformed")
    from .proposal_adoption import _member

    allowed_roots = ("items", "repairs", "repair-history", "repair-budget",
                     "quality", "attack-adjudication", "validated")
    construction_parts = [] if construction_root == "." else construction_root.split("/")
    for name in omitted:
        _member(root, name)
        parts = name.split("/")
        scope = parts[len(construction_parts):]
        if (parts[:len(construction_parts)] != construction_parts or len(scope) < 3
                or scope[0] not in allowed_roots or scope[1] == item_name):
            raise CheckpointRevalidationError(f"checkpoint omission affects selected or shared evidence: {name}")
    if set(files) & set(omitted):
        raise CheckpointRevalidationError("checkpoint member is both declared and omitted")
    for name, expected in files.items():
        if not isinstance(name, str) or re.fullmatch(r"[0-9a-f]{64}", str(expected)) is None:
            raise CheckpointRevalidationError("checkpoint source inventory is malformed")
        path = _member(root, name)
        if not path.is_file() or _sha(path) != expected:
            raise CheckpointRevalidationError(f"checkpoint source member fingerprint differs: {name}")
    actual = _inventory(root)
    if metadata_root is None:
        actual.pop("pull-manifest.json", None)
        actual.pop("snapshot-capture.json", None)
    if actual != files:
        raise CheckpointRevalidationError("checkpoint has missing or undeclared files")
    return files, {"snapshot_id": remote["snapshot_id"], "remote_final": True,
                   "omitted": omitted, "files_verified": len(files)}


def running_controller_provenance() -> dict[str, str]:
    """Fingerprint the maintained controller that will execute fresh gates."""
    package = PROJECT_ROOT / "capability_pipeline"
    files = _source_inventory(package)
    tree = hashlib.sha256(
        "".join(f"{name}\0{files[name]}\n" for name in sorted(files)).encode()
    ).hexdigest()
    return {
        "source_tree_sha256": tree,
        "synthesis_sha256": _sha(Path(__file__).with_name("synthesis.py")),
        "taskcompendium_source_lock_sha256": _sha(SOURCE_LOCK),
        "taskcompendium_overlay_lock_sha256": _sha(
            PROJECT_ROOT / "vendor" / "task_spec" / "composite_extension.lock.json"
        ),
    }


def _validate_bundle(bundle: Path, expected_manifest_sha256: str, expected_request_sha256: str) -> tuple[dict[str, Any], dict[str, Any]]:
    bundle = bundle.resolve()
    manifest_path = bundle / "manifest.json"
    manifest = _read(manifest_path)
    if (not isinstance(manifest, dict) or manifest.get("schema_version") != SCHEMA
            or manifest.get("state") != "prepared_pending_maintained_validation"
            or not isinstance(manifest.get("files"), dict)):
        raise CheckpointRevalidationError("checkpoint bundle manifest has the wrong schema")
    if _sha(manifest_path) != _digest(expected_manifest_sha256, "expected bundle manifest"):
        raise CheckpointRevalidationError("checkpoint bundle manifest differs from expected")
    actual = _inventory(bundle)
    actual.pop("manifest.json", None)
    if manifest["files"] != actual:
        raise CheckpointRevalidationError("checkpoint bundle inventory hash mismatch")
    request_path = bundle / "request.json"
    if _sha(request_path) != _digest(expected_request_sha256, "expected request"):
        raise CheckpointRevalidationError("checkpoint request differs from expected")
    request = _read(request_path)
    if not isinstance(request, dict) or request.get("schema_version") != REQUEST_SCHEMA or request.get("state") != "approved":
        raise CheckpointRevalidationError("checkpoint revalidation request has the wrong schema")
    return manifest, request


def _validate_source(seed: Path, bundle: Path, request: dict[str, Any]) -> dict[str, str]:
    pull_path = bundle / "source-metadata/pull-manifest.json"
    capture_path = bundle / "source-metadata/snapshot-capture.json"
    source = request.get("source")
    if not isinstance(source, dict) or set(source) != {"pull_manifest_sha256", "snapshot_capture_sha256", "source_tree_sha256"}:
        raise CheckpointRevalidationError("checkpoint request source binding is malformed")
    if _sha(pull_path) != _digest(source["pull_manifest_sha256"], "source pull manifest") or _sha(capture_path) != _digest(source["snapshot_capture_sha256"], "source snapshot capture"):
        raise CheckpointRevalidationError("checkpoint source metadata differs from request")
    files, _snapshot = _verify_selective_snapshot(
        seed, request["item_name"], request["construction_root"], bundle / "source-metadata"
    )
    tree = hashlib.sha256("".join(f"{name}\0{files[name]}\n" for name in sorted(files)).encode()).hexdigest()
    if tree != _digest(source["source_tree_sha256"], "source tree"):
        raise CheckpointRevalidationError("checkpoint source tree hash differs from request")
    return files


def _validate_history(root: Path, item_name: str, item: dict[str, Any]) -> tuple[dict[str, Any], tuple[int, ...]]:
    item_root = root / "items" / item_name
    status = _read(item_root / "status.json")
    if not isinstance(status, dict) or status.get("proposal_hash") != item["proposal_hash"]:
        raise CheckpointRevalidationError("checkpoint item status does not bind accepted proposal")
    sessions = status.get("sessions")
    declared = [row.get("session") for row in item["proposal"].get("builder_plan", []) if isinstance(row, dict)]
    if not isinstance(sessions, list) or [row.get("session") for row in sessions if isinstance(row, dict)] != declared:
        raise CheckpointRevalidationError("checkpoint session list differs from builder DAG")
    for name in declared:
        if not isinstance(name, str) or not name or _safe_name(name) != name:
            raise CheckpointRevalidationError("checkpoint builder session name is unsafe")
        persisted = _read(item_root / "sessions" / name / "status.json")
        if not isinstance(persisted, dict) or persisted.get("session") != name or persisted.get("status") != "complete" or _handoff(item_root / "workspace", name) is None:
            raise CheckpointRevalidationError("checkpoint lacks a complete builder handoff")
    repairs = status.get("repairs", [])
    if not isinstance(repairs, list) or any(not isinstance(row, dict) or type(row.get("round")) is not int or row["round"] < 1 for row in repairs):
        raise CheckpointRevalidationError("checkpoint repair history is malformed")
    rounds = tuple(sorted(row["round"] for row in repairs))
    if len(set(rounds)) != len(rounds):
        raise CheckpointRevalidationError("checkpoint repair rounds are duplicated")
    for parent in ("repairs", "repair-history", "repair-budget"):
        names = {path.name for path in (root / parent / item_name).glob("attempt-*") if path.is_dir()}
        if names != {f"attempt-{round_}" for round_ in rounds}:
            raise CheckpointRevalidationError("checkpoint repair tree does not match status")
    budget = status.get("repair_budget")
    if not isinstance(budget, dict) or budget.get("used") != (max(rounds, default=0)):
        raise CheckpointRevalidationError("checkpoint repair budget is missing or reset")
    return status, rounds


def validate_checkpoint_bundle(bundle: Path, *, expected_manifest_sha256: str, expected_request_sha256: str) -> CheckpointRevalidationPlan:
    """Validate a complete immutable checkpoint before any fresh gates run."""
    bundle = Path(bundle).resolve()
    _manifest, request = _validate_bundle(
        bundle, expected_manifest_sha256, expected_request_sha256
    )
    item_name = request.get("item_name")
    if not isinstance(item_name, str) or not item_name or _safe_name(item_name) != item_name:
        raise CheckpointRevalidationError("checkpoint item name is unsafe")
    source_provenance = _require_provenance(request.get("source_controller"), "source")
    construction_name = request.get("construction_root")
    construction_path = Path(construction_name) if isinstance(construction_name, str) else None
    if (construction_path is None or construction_path.is_absolute()
            or (not construction_path.parts and construction_name != ".")
            or ".." in construction_path.parts or construction_path.as_posix() != construction_name):
        raise CheckpointRevalidationError("checkpoint construction root is unsafe")
    seed = bundle / "restore-seed"
    _validate_source(seed, bundle, request)
    construction_root = seed / construction_path
    if construction_root.is_symlink() or not construction_root.is_dir():
        raise CheckpointRevalidationError("checkpoint construction root is unavailable")
    accepted = load_accepted(bundle / "accepted.json", 1)
    if len(accepted) != 1 or not item_name.endswith(accepted[0]["proposal_hash"][:12]):
        raise CheckpointRevalidationError("checkpoint accepted proposal does not bind item")
    item = accepted[0]
    if _read(construction_root / "items" / item_name / "contract/accepted.json") != item:
        raise CheckpointRevalidationError("checkpoint accepted contract differs from accepted input")
    _status, rounds = _validate_history(construction_root, item_name, item)
    item_root = construction_root / "items" / item_name
    workspace = tuple(
        sorted(
            (f"workspace/{path}", digest)
            for path, digest in _inventory(item_root / "workspace").items()
            if not path.startswith("tools/daytona/")
        )
    )
    sessions = tuple(
        sorted(
            (f"sessions/{path}", digest)
            for path, digest in _inventory(item_root / "sessions").items()
        )
    )
    repair_files: list[tuple[str, str]] = []
    for parent in ("repairs", "repair-history", "repair-budget"):
        root = construction_root / parent / item_name
        if root.exists():
            repair_files.extend(
                (f"{construction_name}/{parent}/{item_name}/{name}", digest)
                for name, digest in _inventory(root).items()
            )
    return CheckpointRevalidationPlan(
        bundle,
        seed,
        construction_path,
        item_name,
        item,
        rounds,
        workspace,
        sessions,
        tuple(sorted(repair_files)),
        _sha(item_root / "contract" / "accepted.json"),
        source_provenance,
        _sha(bundle / "request.json"),
        _sha(bundle / "manifest.json"),
    )


def _verify_inventory(
    root: Path,
    expected: tuple[tuple[str, str], ...],
    label: str,
    *,
    ignored_prefixes: tuple[str, ...] = (),
) -> None:
    actual = tuple(
        sorted(
            (relative, digest)
            for relative, digest in _inventory(root).items()
            if not any(relative.startswith(prefix) for prefix in ignored_prefixes)
        )
    )
    if actual != expected:
        raise CheckpointRevalidationError(
            f"maintained gate changed protected {label} inventory"
        )


def prepare_checkpoint_revalidation(plan: CheckpointRevalidationPlan, output: Path, *, new_controller: dict[str, Any]) -> PreparedCheckpointRevalidation:
    """Create a new output prefix and archive prior gate evidence before replay."""
    output = Path(output).resolve()
    if output.exists():
        raise CheckpointRevalidationError("checkpoint revalidation output must be new")
    new_provenance = _require_provenance(new_controller, "new")
    if new_provenance != running_controller_provenance():
        raise CheckpointRevalidationError("new controller provenance differs from running source")
    shutil.copytree(plan.restore_seed, output, copy_function=shutil.copy2)
    construction = output / plan.construction_root
    item_root = output / plan.construction_root / "items" / plan.item_name
    history = output / "checkpoint-revalidation-history" / plan.item_name / "attempt-1"
    history.mkdir(parents=True)
    shutil.copy2(item_root / "status.json", history / "status.json")
    controller_history = history / "controller"
    controller_history.mkdir()
    for parent, names in (
        (
            output,
            (
                "generate-run.json",
                "report.json",
                "proposal-receipt.json",
                "construction-receipt.json",
                "construction-progress.json",
            ),
        ),
        (construction, ("run.json", "report.json", "tasks.json")),
    ):
        for name in names:
            source = parent / name
            if source.is_file():
                shutil.move(str(source), controller_history / f"{parent.name}-{name}")
    for name in ("harbor", "runtime-trials", "judge-calibration", "diagnostics", "runtime-evidence.json", "solver-transcripts.json", "independent-adversary.json", "authored-oracle.json"):
        source = item_root / name
        if source.exists():
            shutil.move(str(source), history / name)
    for name in ("quality", "attack-adjudication", "validated"):
        source = construction / name / plan.item_name
        if source.exists():
            destination = history / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(source), destination)
    frozen = output / "checkpoint-revalidation-input"
    frozen.mkdir()
    for name in ("manifest.json", "request.json", "accepted.json"):
        shutil.copy2(plan.bundle / name, frozen / name)
    shutil.copytree(plan.bundle / "source-metadata", frozen / "source-metadata")
    operation_path = output / "controller" / "checkpoint-revalidation.json"
    operation = {"schema_version": "capability-checkpoint-revalidation-v1", "state": "prepared", "item_name": plan.item_name, "source_provenance": plan.source_provenance, "new_controller": new_provenance, "source_bundle_manifest_sha256": plan.bundle_manifest_sha256, "request_sha256": plan.request_sha256, "consumed_repair_rounds": list(plan.repair_rounds), "semantic_repair_performed": False, "maintained_gate_attempts": 0, "prior_gate_archive": str(history), "started_at": datetime.now(UTC).isoformat(), "completed_at": None, "result": None}
    atomic_json(operation_path, operation)
    prior = _read(history / "status.json")
    atomic_json(item_root / "status.json", {"key": prior.get("key"), "proposal_hash": plan.item["proposal_hash"], "sessions": prior.get("sessions", []), "repairs": prior.get("repairs", []), "repair_budget": prior.get("repair_budget"), "state": "pending_checkpoint_revalidation", "issues": ["fresh maintained gates have not started; prior status is archived"], "checkpoint_revalidation": {"operation_state": "prepared", "operation_artifact": str(operation_path.relative_to(output)), "prior_status_artifact": str((history / "status.json").relative_to(output)), "prior_status_sha256": _sha(history / "status.json")}})
    return PreparedCheckpointRevalidation(plan, output, item_root, history, operation_path, prior)


def run_prepared_checkpoint_revalidation(prepared: PreparedCheckpointRevalidation, attempt: Callable[[dict[str, Any], Path], dict[str, Any]]) -> dict[str, Any]:
    """Run exactly one maintained gate attempt and prohibit repair/history mutation."""
    operation = _read(prepared.operation_path)
    if operation.get("state") != "prepared":
        raise CheckpointRevalidationError("checkpoint revalidation is not prepared")
    operation["state"] = "running"
    atomic_json(prepared.operation_path, operation)
    status = _read(prepared.item_root / "status.json")
    status["state"] = "checkpoint_revalidation_running"
    status["checkpoint_revalidation"]["operation_state"] = "running"
    atomic_json(prepared.item_root / "status.json", status)
    try:
        result = attempt(prepared.plan.item, prepared.root)
        if not isinstance(result, dict) or not isinstance(result.get("state"), str):
            raise CheckpointRevalidationError("maintained gate returned an invalid result")
        _verify_inventory(
            prepared.item_root / "workspace",
            tuple(
                (relative.removeprefix("workspace/"), digest)
                for relative, digest in prepared.plan.protected_workspace
            ),
            "workspace",
            ignored_prefixes=("tools/daytona/",),
        )
        _verify_inventory(
            prepared.item_root / "sessions",
            tuple(
                (relative.removeprefix("sessions/"), digest)
                for relative, digest in prepared.plan.protected_sessions
            ),
            "session",
        )
        repair_actual: list[tuple[str, str]] = []
        construction = prepared.root / prepared.plan.construction_root
        for parent in ("repairs", "repair-history", "repair-budget"):
            root = construction / parent / prepared.plan.item_name
            names = {path.name for path in root.glob("attempt-*") if path.is_dir()}
            if names != {f"attempt-{round_}" for round_ in prepared.plan.repair_rounds}:
                raise CheckpointRevalidationError("maintained gate changed protected repair rounds")
            if root.exists():
                repair_actual.extend(
                    (f"{prepared.plan.construction_root}/{parent}/{prepared.plan.item_name}/{name}", digest)
                    for name, digest in _inventory(root).items()
                )
        if tuple(sorted(repair_actual)) != prepared.plan.protected_repairs:
            raise CheckpointRevalidationError("maintained gate changed protected repair history inventory")
        accepted = prepared.item_root / "contract" / "accepted.json"
        if not accepted.is_file() or _sha(accepted) != prepared.plan.accepted_contract_sha256:
            raise CheckpointRevalidationError("maintained gate changed accepted contract")
        result["repairs"] = prepared.prior_status.get("repairs", [])
        result["repair_budget"] = prepared.prior_status.get("repair_budget")
        result["checkpoint_revalidation"] = {"source_bundle_manifest_sha256": prepared.plan.bundle_manifest_sha256, "request_sha256": prepared.plan.request_sha256, "prior_gate_archive": str(prepared.history_root), "consumed_repair_rounds": list(prepared.plan.repair_rounds), "semantic_repair_performed": False, "maintained_gate_attempts": 1}
        atomic_json(prepared.item_root / "status.json", result)
        atomic_json(prepared.root / prepared.plan.construction_root / "tasks.json", [result])
        operation.update(state="completed", completed_at=datetime.now(UTC).isoformat(), maintained_gate_attempts=1, result={"state": result["state"], "status_sha256": _sha(prepared.item_root / "status.json")})
        atomic_json(prepared.operation_path, operation)
        return result
    except Exception as error:
        operation.update(state="error", completed_at=datetime.now(UTC).isoformat(), result={"exception_type": type(error).__name__})
        atomic_json(prepared.operation_path, operation)
        export = prepared.root / prepared.plan.construction_root / "validated" / prepared.plan.item_name
        if export.exists():
            quarantine = prepared.history_root / "quarantined-export"
            if quarantine.exists():
                shutil.rmtree(quarantine)
            shutil.move(str(export), quarantine)
        atomic_json(
            prepared.item_root / "status.json",
            {
                "key": prepared.prior_status.get("key"),
                "proposal_hash": prepared.plan.item["proposal_hash"],
                "sessions": prepared.prior_status.get("sessions", []),
                "repairs": prepared.prior_status.get("repairs", []),
                "repair_budget": prepared.prior_status.get("repair_budget"),
                "state": "checkpoint_revalidation_error",
                "issues": [f"maintained gate raised {type(error).__name__}"],
                "checkpoint_revalidation": {
                    "operation_state": "error",
                    "operation_artifact": str(prepared.operation_path.relative_to(prepared.root)),
                    "prior_gate_archive": str(prepared.history_root),
                    "semantic_repair_performed": False,
                },
            },
        )
        raise
