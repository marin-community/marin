"""Train a fresh Mochi draft from immutable regional verifier captures."""

import hashlib
import json
import logging
import shutil
import tempfile
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from marinskyrl.speculative_decoding import SpeculatorModelConfig, SpeculatorTrainingConfig
from rigging.filesystem.storage_path import StoragePath, prefix_join
from safetensors import safe_open
from safetensors.torch import load_file, save_file
from skyrl_train.inference_engines.vllm.online_eagle_trainer import (
    OnlineEagleTrainerRuntime,
    OnlineEagleTrainingJob,
    merge_online_eagle_captures,
    partition_capture_windows,
)
from skyrl_train.io import io

from experiments.post_training.mochi_eagle3 import TARGET_IDENTITY, initialize_draft, worker_spec

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class PreparedDraftTraining:
    job: OnlineEagleTrainingJob
    seed: Path
    fold: dict


def prepare_training_capture(spec: dict, directory: Path) -> PreparedDraftTraining:
    """Bind immutable captured features to a vocabulary selected from the training fold."""
    captures = directory / "ranks"
    io.download_directory(spec["captures"], str(captures))
    merged = directory / "training-capture"
    manifest = merge_online_eagle_captures(
        captures,
        merged,
        expected_step=1,
        max_tokens=spec["max_tokens"],
        max_sequences_per_prompt_group=1,
        max_window_tokens=spec["window_tokens"],
    )
    if manifest["target_revision"] != TARGET_IDENTITY:
        raise ValueError("Capture was not generated by the adopted Mochi target")
    training = SpeculatorTrainingConfig(
        max_tokens_per_update=spec["max_tokens"],
        max_window_tokens=spec["window_tokens"],
        max_tokens_per_micro_batch=spec["window_tokens"],
        max_sequences_per_prompt_group=1,
        epochs_per_update=spec["epochs"],
        learning_rate=spec["learning_rate"],
    )
    train_windows, heldout = partition_capture_windows(
        manifest["windows"],
        step=1,
        holdout_fraction=training.holdout_fraction,
        min_train_sequences=training.min_train_sequences,
        min_holdout_sequences=training.min_holdout_sequences,
    )
    frequencies: Counter[int] = Counter()
    for window in train_windows:
        with safe_open(merged / window["path"], framework="pt") as tensors:
            tokens = tensors.get_tensor("input_ids")
            mask = tensors.get_tensor("loss_mask")
            frequencies.update(tokens[mask].tolist())
    if not frequencies:
        raise ValueError("Training fold has no continuation tokens")
    seed_root = directory / "fresh-seed"
    seed_root.mkdir()
    initialization = initialize_draft(seed_root, frequencies, spec["seed"])
    seed = seed_root / "seed-draft"
    seed_weights = load_file(seed / "model.safetensors")
    map_digest = hashlib.sha256(seed_weights["d2t"].numpy().tobytes()).hexdigest()
    # Features and embeddings are unchanged. Reproject only the frozen head to
    # the training-fold vocabulary, preserving the raw rank captures intact.
    target_weights = load_file(merged / "target.safetensors")
    target_weights["lm_head.weight"] = seed_weights["lm_head.weight"]
    save_file(target_weights, merged / "target.safetensors", metadata={"format": "pt"})
    del target_weights, seed_weights
    split = {
        "training_groups": sorted({window["group_id"] for window in train_windows}),
        "heldout_groups": sorted({window["group_id"] for window in heldout}),
        "training_continuation_tokens": frequencies.total(),
        "vocabulary_map_sha256": map_digest,
        "initialization": initialization,
        "source": spec,
    }
    (merged / "mochi-training-fold.json").write_text(json.dumps(split, indent=2))
    io.upload_directory(str(merged), prefix_join(spec["output"], "training-capture"))
    job = OnlineEagleTrainingJob(
        step=1,
        capture_dir=str(merged),
        initial_draft_model=SpeculatorModelConfig(str(seed), f"sha256:{map_digest}"),
        parent_draft_revision="fresh-h6144-one-layer",
        target_revision=TARGET_IDENTITY,
        output_dir=str(directory / "candidate"),
        num_speculative_tokens=3,
        seed=spec["seed"],
        training=training,
    )
    return PreparedDraftTraining(job, seed, split)


def publish_serving_draft(candidate: Path, seed: Path, output: str, receipt: dict) -> None:
    """Publish trainable weights, vocabulary maps, and the frozen projected Mochi head."""
    bundle = candidate.parent / "serving-draft"
    bundle.mkdir()
    shutil.copyfile(candidate / "config.json", bundle / "config.json")
    weights = load_file(candidate / "model.safetensors")
    with safe_open(seed / "model.safetensors", framework="pt") as initial:
        weights["lm_head.weight"] = initial.get_tensor("lm_head.weight")
    if not {"t2d", "d2t", "lm_head.weight"}.issubset(weights):
        raise ValueError("Standalone draft is missing its vocabulary maps or projected target head")
    save_file(weights, bundle / "model.safetensors", metadata={"format": "pt"})
    (bundle / "lineage.json").write_text(json.dumps(receipt, indent=2))
    io.upload_directory(str(bundle), prefix_join(output, "serving-draft"))


def train(spec: dict, directory: Path) -> None:
    """Run and gate one offline draft update before publishing its serving bundle."""
    prepared = prepare_training_capture(spec, directory)
    job = prepared.job
    runtime = OnlineEagleTrainerRuntime(job, Path(job.capture_dir))
    result = runtime.update(job)
    receipt = {"training": result.to_mapping(), "fold": prepared.fold}
    (StoragePath(spec["output"]) / "result.json").write_text(json.dumps(receipt, indent=2))
    if not result.accepted:
        raise ValueError(f"Draft failed same-holdout improvement gate: {result.to_mapping()}")
    candidate = Path(job.output_dir)
    io.upload_directory(str(candidate), prefix_join(spec["output"], "trainer-checkpoint"))
    publish_serving_draft(candidate, prepared.seed, spec["output"], receipt)
    logger.info("Published trained draft: %s", json.dumps(result.to_mapping()))


def main() -> None:
    spec = worker_spec(__doc__)
    if not spec["output"].startswith("s3://marin-us-east-08a/"):
        raise ValueError("Mochi training artifacts must remain in regional 08a S3")
    with tempfile.TemporaryDirectory(prefix="mochi-eagle3-training-") as scratch:
        train(spec, Path(scratch))


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    main()
