class CurriculumSftData(Artifact):
    """Canonical OpenAI-message conversations and their generation provenance."""

    @property
    def training_uri(self) -> str:
        return prefix_join(self.path, TRAIN_FILENAME)

    @property
    def manifest_uri(self) -> str:
        return prefix_join(self.path, MANIFEST_FILENAME)


@dataclass(frozen=True)
class CurriculumSftRequest:
    """Curriculum selection and synthetic task family for one data arm."""

    subject_id: str
    capability_ids: tuple[str, ...]
    task: str
    evaluation_area: str


@dataclass(frozen=True)
class RolloutGenerationConfig:
    catalog_uri: str
    output_path: str
    request: CurriculumSftRequest
    sample_count: int
    request_batch_size: int
    seed: int
    relay_job: str
    poll_seconds: float


@dataclass(frozen=True)
class StaticEvaluationModel:
    model: ModelConfig

    def deps(self) -> tuple[ArtifactStep, ...]:
        return ()

    def resolve(self, _ctx: StepContext) -> ModelConfig:
        return self.model


@dataclass(frozen=True)
class CurriculumSftPipeline:
    data: ArtifactStep[CurriculumSftData]
    baseline: ArtifactStep[EvaluationResult]
    sft: ArtifactStep[LevanterCheckpoint]
    reevaluation: ArtifactStep[EvaluationResult]


def subject_and_capabilities(
    catalog: CurriculumCatalog, subject_id: str, capability_ids: tuple[str, ...]
) -> tuple[str, list[CapabilitySection]]:
    entries = [entry.curriculum for entry in catalog.curricula if entry.curriculum.subject_id == subject_id]
    if len(entries) != 1:
        raise ValueError(f"expected one curriculum for subject {subject_id}, found {len(entries)}")
    curriculum = entries[0]
    capabilities = {section.id: section for section in curriculum.capability_sections()}
    unknown = sorted(set(capability_ids) - capabilities.keys())
    if unknown:
        raise ValueError(f"unknown capabilities for {subject_id}: {unknown}")
    if not capability_ids:
        raise ValueError("select at least one capability")
    return curriculum.subject_name, [capabilities[capability_id] for capability_id in capability_ids]


def _capability_packet(capabilities: list[CapabilitySection]) -> list[dict[str, Any]]:
    return [
        {
            "id": capability.id,
            "name": capability.name,
            "outcome": capability.outcome,
            "includes": capability.includes,
            "excludes": capability.excludes,
            "sampling_facets": [facet.model_dump(mode="json") for facet in capability.sampling_facets],
            "sample_tasks": [task.model_dump(mode="json") for task in capability.sample_tasks],
        }
        for capability in capabilities
    ]


def example_tool_schema(expected_examples: int) -> dict[str, Any]:
    return {
        "type": "object",
        "additionalProperties": False,
        "required": ["examples"],
        "properties": {
            "examples": {
                "type": "array",
                "minItems": expected_examples,
                "maxItems": expected_examples,
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["id", "task_summary", "user", "assistant", "verification"],
                    "properties": {
                        "id": {"type": "integer", "enum": list(range(expected_examples))},
                        "task_summary": {"type": "string", "minLength": 1},
                        "user": {"type": "string", "minLength": 1},
                        "assistant": {"type": "string", "minLength": 1},
                        "verification": {"type": "string", "minLength": 1},
                    },
                },
            }
        },
    }


def completion_body(
    *,
    subject_name: str,
    capabilities: list[CapabilitySection],
    task: str,
    evaluation_area: str,
    expected_examples: int,
    seed: int,
) -> dict[str, Any]:
    prompt = {
        "subject": subject_name,
        "capabilities": _capability_packet(capabilities),
        "task_family": task,
        "evaluation_area": evaluation_area,
        "examples": expected_examples,
        "seed": seed,
    }
    instructions = (
        "Create diverse supervised fine-tuning conversations from the supplied curriculum packet. "
        "Each example must contain one user message and one assistant message. Invent every name, document, "
        "fact, and number. Include all evidence needed to solve the task in the user message. The assistant must "
        "show a correct, concise derivation and answer. Do not quote, reconstruct, search for, or imitate any "
        "evaluation question or benchmark instruction. Treat evaluation_area only as a broad skill label. Keep "
        "examples inside the selected capabilities and their explicit includes/excludes. Make each verification "
        "field state an independent arithmetic, logical, or evidence check that a later filter can apply."
    )
    return {
        "model": MODEL,
        "messages": [
            {"role": "system", "content": instructions},
            {"role": "user", "content": json.dumps(prompt, ensure_ascii=False, separators=(",", ":"))},
        ],
        "tools": [
            {
                "type": "function",
                "function": {
                    "name": "submit_examples",
                    "description": "Submit the requested curriculum-grounded SFT conversations.",
                    "strict": True,
                    "parameters": example_tool_schema(expected_examples),
                },
            }
        ],
        "tool_choice": {"type": "function", "function": {"name": "submit_examples"}},
        "parallel_tool_calls": False,
        "chat_template_kwargs": {"reasoning_effort": "low"},
        "prompt_cache_key": f"curriculum-sft-{capabilities[0].id.split('.', 1)[0]}",
        "max_tokens": 16000,
    }


def batch_lines(
    *,
    subject_name: str,
    capabilities: list[CapabilitySection],
    task: str,
    evaluation_area: str,
    sample_count: int,
    request_batch_size: int,
    seed: int,
) -> tuple[list[dict[str, Any]], dict[str, tuple[int, int]]]:
    lines = []
    requests = {}
    for start in range(0, sample_count, request_batch_size):
        count = min(request_batch_size, sample_count - start)
        custom_id = f"examples-{start:06d}-{count:02d}"
        lines.append(
            {
                "custom_id": custom_id,
                "method": "POST",
                "url": "/v1/chat/completions",
                "body": completion_body(
                    subject_name=subject_name,
                    capabilities=capabilities,
                    task=task,
                    evaluation_area=evaluation_area,
                    expected_examples=count,
                    seed=seed + start,
                ),
            }
        )
        requests[custom_id] = (start, count)
    return lines, requests


def parse_batch_output(
    output: str,
    requests: dict[str, tuple[int, int]],
    *,
    request: CurriculumSftRequest,
) -> list[dict[str, Any]]:
    rows = []
    seen = set()
    for line in output.splitlines():
        if not line.strip():
            continue
        response = json.loads(line)
        custom_id = response["custom_id"]
        if custom_id not in requests or custom_id in seen:
            raise ValueError(f"unexpected or duplicate GLM response {custom_id}")
        seen.add(custom_id)
        start, count = requests[custom_id]
        result = response.get("response") or {}
        if response.get("error") or result.get("status_code") != 200:
            raise RuntimeError(f"GLM request {custom_id} failed")
        examples = tool_arguments(result["body"], "submit_examples")["examples"]
        if not isinstance(examples, list):
            raise ValueError(f"GLM request {custom_id} returned examples as {type(examples).__name__}, expected array")
        if len(examples) != count:
            raise ValueError(f"GLM request {custom_id} returned {len(examples)} examples, expected {count}")
        by_id = {example["id"]: example for example in examples}
        if set(by_id) != set(range(count)):
            raise ValueError(f"GLM request {custom_id} returned invalid example IDs")
        for local_id in range(count):
            example = by_id[local_id]
            messages = [
                {"role": "user", "content": example["user"]},
                {"role": "assistant", "content": example["assistant"]},
            ]
            global_id = start + local_id
            digest = hashlib.sha256(
                json.dumps(messages, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()
            ).hexdigest()
            rows.append(
                {
                    "id": f"curriculum-sft-{digest[:24]}",
                    "messages": messages,
                    "metadata": {
                        "policy_version": POLICY_VERSION,
                        "generator": MODEL,
                        "subject_id": request.subject_id,
                        "capability_ids": list(request.capability_ids),
                        "task_family": request.task,
                        "evaluation_area": request.evaluation_area,
                        "sample_index": global_id,
                        "task_summary": example["task_summary"],
                        "verification": example["verification"],
                    },
                }
            )
    missing = sorted(set(requests) - seen)
    if missing:
        raise ValueError(f"GLM batch omitted {len(missing)} requests")
    rows.sort(key=lambda row: row["metadata"]["sample_index"])
    return rows


def run_generation(config: RolloutGenerationConfig) -> CurriculumSftData:
    output = StoragePath(config.output_path)
    output.mkdirs()
    manifest_path = output / MANIFEST_FILENAME
    if manifest_path.exists():
        return CurriculumSftData(path=config.output_path)

    catalog_bytes = StoragePath(config.catalog_uri).read_bytes()
    catalog = CurriculumCatalog.model_validate_json(catalog_bytes)
    subject_name, capabilities = subject_and_capabilities(
        catalog,
        config.request.subject_id,
        config.request.capability_ids,
    )
    lines, requests = batch_lines(
        subject_name=subject_name,
        capabilities=capabilities,
        task=config.request.task,
        evaluation_area=config.request.evaluation_area,
        sample_count=config.sample_count,
        request_batch_size=config.request_batch_size,
        seed=config.seed,
    )
    (output / REQUESTS_FILENAME).write_text(jsonl_text(lines))

    state_path = output / "batch-state.json"
    base_url = resolve_base_url(config.relay_job)
    token = os.environ[GLM_BULK_TOKEN_ENV]
    if state_path.exists():
        state = json.loads(state_path.read_text())
        file_id, batch_id = state["file_id"], state["batch_id"]
    else:
        file_id, batch_id = submit_batch(base_url, token, lines, "curriculum-sft-examples.jsonl")
        state_path.write_text(json.dumps({"file_id": file_id, "batch_id": batch_id}, indent=2) + "\n")

    batch = wait_for_batch(base_url, token, batch_id, config.poll_seconds)
    raw_output, raw_errors = read_batch_output(base_url, token, batch)
    (output / RAW_OUTPUT_FILENAME).write_text(raw_output)
    if raw_errors is not None:
        (output / "raw-errors.jsonl").write_text(raw_errors)
    rows = parse_batch_output(
        raw_output,
        requests,
        request=config.request,
    )
    if len(rows) != config.sample_count:
        raise ValueError(f"generated {len(rows)} examples, expected {config.sample_count}")
    if len({row["id"] for row in rows}) != len(rows):
        raise ValueError("generated conversations contain duplicates")

    training_path = output / TRAIN_FILENAME
    training_path.parent.mkdirs()
    with training_path.open("wb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as compressed:
            compressed.write(jsonl_text(rows).encode())
    manifest = {
        "policy_version": POLICY_VERSION,
        "generator": MODEL,
        "catalog_uri": config.catalog_uri,
        "catalog_sha256": hashlib.sha256(catalog_bytes).hexdigest(),
        "subject_id": config.request.subject_id,
        "subject_name": subject_name,
        "capability_ids": list(config.request.capability_ids),
        "task_family": config.request.task,
        "evaluation_area": config.request.evaluation_area,
        "sample_count": len(rows),
        "seed": config.seed,
        "glm_batch_id": batch_id,
        "training_file": TRAIN_FILENAME,
    }
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return CurriculumSftData(path=config.output_path)


def generation_step(
    *,
    request: CurriculumSftRequest,
    sample_count: int,
    version: str,
    request_batch_size: int = DEFAULT_BATCH_SIZE,
    seed: int = DEFAULT_SEED,
    relay_job: str = DEFAULT_RELAY_JOB,
    poll_seconds: float = DEFAULT_POLL_SECONDS,
) -> ArtifactStep[CurriculumSftData]:
    if sample_count < 1:
        raise ValueError("sample_count must be positive")
    if request_batch_size < 1:
        raise ValueError("request_batch_size must be positive")

    def build_config(ctx: StepContext) -> RolloutGenerationConfig:
        return RolloutGenerationConfig(
            catalog_uri=prefix_join(ctx.artifact_path(TASK_CURRICULUM), "curriculum.json"),
            output_path=ctx.output_path,
            request=request,
            sample_count=sample_count,
            request_batch_size=request_batch_size,
            seed=seed,
            relay_job=relay_job,
            poll_seconds=poll_seconds,
        )

    return ArtifactStep(
        name=user_owned_name(f"documents/curriculum-sft/{request.subject_id.lower()}"),
        version=version,
        artifact_type=CurriculumSftData,
        run=run_generation,
        build_config=build_config,
        deps=(TASK_CURRICULUM,),
    )


def _qwen_model(name: str, location: str) -> ModelConfig:
    return ModelConfig(
        name=name,
        location=location,
        revision=QWEN3_REVISION if location == QWEN3_MODEL else None,
        tokenizer=QWEN3_MODEL,
        apply_chat_template=True,
        resource_hint=ResourceHint(gpu={"H100": 1}),
        generation=GenerationConfig(max_gen_toks=4096),
    )


def build_pipeline(
    *,
    request: CurriculumSftRequest,
    eval_config: Path,
    sample_count: int,
    version: str,
) -> CurriculumSftPipeline:
    data = generation_step(
        request=request,
        sample_count=sample_count,
        version=version,
    )
    base_name = f"curriculum-sft-{request.subject_id.lower()}-qwen3-0.6b-base"
    baseline = evalchemy_config_step(
        StaticEvaluationModel(_qwen_model(base_name, QWEN3_MODEL)),
        eval_config,
        version=version,
        accelerator="H100x1",
        submission_cluster=QWEN_EXECUTION_CLUSTER,
        federated_cluster=None,
    )
    checkpoint_name = user_owned_name(f"checkpoints/curriculum-sft/{request.subject_id.lower()}-qwen3-0.6b")
    sft = sft_step(
        SFTSpec(
            name=checkpoint_name,
            version=version,
            model=HFModel(
                model_ref=f"{QWEN3_MODEL}@{QWEN3_REVISION}",
                tokenizer_path=QWEN3_MODEL,
                eos_token_ids=(151643, 151645),
            ),
            chat_template=QWEN3_CHAT_TEMPLATE,
            datasets=(
                ArtifactDatasetSpec(
                    slug=f"curriculum-{request.subject_id.lower()}",
                    artifact=data,
                    relative_pattern=TRAIN_FILENAME,
                    weight=1.0,
                ),
            ),
            optimizer=AdamConfig(
                learning_rate=1e-5,
                beta1=0.9,
                beta2=0.98,
                epsilon=1e-8,
                max_grad_norm=1.0,
                weight_decay=0.0,
                lr_schedule="cosine",
                warmup=0.1,
                min_lr_ratio=0.0,
            ),
            seq_len=8192,
            batch_size=8,
            num_train_steps=16,
            wandb_project="marin-curriculum-sft",
        ),
        resources_from_accelerator("1xH100"),
    )
    post_name = f"curriculum-sft-{request.subject_id.lower()}-qwen3-0.6b"
    reevaluation = evalchemy_config_step(
        ProducedEvaluationModel(sft, _qwen_model(post_name, "artifact://pending")),
        eval_config,
        version=version,
        accelerator="H100x1",
        submission_cluster=QWEN_EXECUTION_CLUSTER,
        federated_cluster=None,
    )
    return CurriculumSftPipeline(data=data, baseline=baseline, sft=sft, reevaluation=reevaluation)


@click.command(help=__doc__)
@click.option("--subject", "subject_id", default=DEFAULT_SUBJECT, show_default=True)
@click.option("--capability", "capability_ids", multiple=True, default=DEFAULT_CAPABILITIES, show_default=True)
@click.option("--task", default=DEFAULT_TASK, show_default=True)
@click.option("--evaluation-area", default="financial question answering", show_default=True)
@click.option(
    "--eval-config",
    type=click.Path(path_type=Path, exists=True, dir_okay=False),
    default=DEFAULT_EVAL_CONFIG,
    show_default=True,
)
@click.option("--sample-count", type=click.IntRange(min=1), default=DEFAULT_SAMPLE_COUNT, show_default=True)
@click.option(
    "--stage",
    type=click.Choice(("data", "baseline", "sft", "reevaluation", "all")),
    default="all",
    show_default=True,
)
@build_options
def main(
    subject_id: str,
    capability_ids: tuple[str, ...],
    task: str,
    evaluation_area: str,
    eval_config: Path,
    sample_count: int,
    stage: str,
) -> ArtifactStep | dict[str, ArtifactStep]:
    base_name = f"documents/curriculum-sft/{subject_id.lower()}"
    version = resolve_version(base_name, None)
    pipeline = build_pipeline(
        request=CurriculumSftRequest(
            subject_id=subject_id,
            capability_ids=capability_ids,
            task=task,
            evaluation_area=evaluation_area,
        ),
        eval_config=eval_config,
        sample_count=sample_count,
        version=version,
    )
    if stage == "all":
        return {"baseline": pipeline.baseline, "reevaluation": pipeline.reevaluation}
    return getattr(pipeline, stage)


if __name__ == "__main__":
    main()
