def _quality_domain_weights() -> dict[str, float]:
    phase_weights = _phase_weights(1)
    tail_weight = phase_weights.pop("tail")
    token_counts = {bucket: short_tokens + long_tokens for bucket, short_tokens, long_tokens in _BUCKET_LENGTH_TOKENS}
    tail_tokens = sum(token_counts[bucket] for bucket in _TAIL_BUCKETS)
    return {
        **phase_weights,
        **{bucket: tail_weight * token_counts[bucket] / tail_tokens for bucket in _TAIL_BUCKETS},
    }


def _component_name(bucket: str, length_bucket: str) -> str:
    return f"{bucket}-{length_bucket}"


def _bucket_component(bucket: str, length_bucket: str) -> DatasetComponent:
    cluster = int(bucket[1:3])
    quality = int(bucket[-1])
    cache_dir = f"{LONG_CONTEXT_STORE_PREFIX}/cluster={cluster}/quality={quality}/length={length_bucket}"
    return DatasetComponent(
        source=None,
        cache_dir=cache_dir,
        format=TextLmDatasetFormat(),
        tags=[bucket, length_bucket],
        flat_cache=True,
    )


def long_context_phase_weights(skew: float = LONG_CONTEXT_SKEW) -> dict[str, float]:
    """Apply a relative long-document multiplier without changing quality-by-domain mass."""
    if skew <= 0:
        raise ValueError("long-context skew must be positive")

    quality_domain_weights = _quality_domain_weights()
    weights = {}
    for bucket, short_tokens, long_tokens in _BUCKET_LENGTH_TOKENS:
        bucket_weight = quality_domain_weights[bucket]
        skewed_tokens = short_tokens + skew * long_tokens
        weights[_component_name(bucket, _LTE_64K)] = bucket_weight * short_tokens / skewed_tokens
        if long_tokens:
            weights[_component_name(bucket, _GT_64K)] = bucket_weight * skew * long_tokens / skewed_tokens
    return weights


def long_context_datakit_components() -> dict[str, DatasetComponent]:
    """Return one component for every populated quality, domain, and length cell."""
    components = {}
    for bucket, _, long_tokens in _BUCKET_LENGTH_TOKENS:
        components[_component_name(bucket, _LTE_64K)] = _bucket_component(bucket, _LTE_64K)
        if long_tokens:
            components[_component_name(bucket, _GT_64K)] = _bucket_component(bucket, _GT_64K)
    return components


def _validate_mixture() -> None:
    buckets = {bucket for bucket, _, _ in _BUCKET_LENGTH_TOKENS}
    if len(buckets) != len(_BUCKET_LENGTH_TOKENS) or buckets != set(_quality_domain_weights()):
        raise ValueError("token counts do not match the second-phase quality-by-domain buckets")
    if not math.isclose(sum(long_context_phase_weights().values()), 1.0, abs_tol=1e-12):
        raise ValueError("long-context mixture weights do not sum to one")


_validate_mixture()
