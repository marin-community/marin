"""Emit a drop-in ``dt.py`` backed by silo instead of Daytona.

    uv run python -m silo.dt_shim --tools-src ~/openathena/build_envs/envgen --tools-out /path/tools

``--tools-src`` is a directory holding the maintained Daytona tools (dt.py, dt.sh,
validate_env.py, verify.py, adapter.py -- the set synthesis.py stages). The
output directory gets the same files, with dt.py replaced.

The new dt.py is the ORIGINAL dt.py -- same CLI, same JSON output, same call log
that build reports are checked against -- with exactly three changes:

  1. ``client()`` returns a silo client configured from SILO_API_TOKEN and
     SILO_BROKER_RESOLVE_URL (or SILO_BROKER_URL).
  2. The snapshot budget/quota wait in ``snapshot build`` is disabled. It
     throttled builds against Daytona's 40-snapshot org quota; there is no such
     quota here, and leaving the wait in would reimpose the very ceiling this
     provider exists to remove.
  3. The silo client is embedded as source, because dt.py travels as one
     hash-pinned file (generic_image_capture.py pins its sha256).

Each change is an exact-match substitution against the original text, and
generation fails if any anchor is missing, so an upstream edit to dt.py cannot be
patched silently in the wrong place.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
from pathlib import Path

_SILO = Path(__file__).resolve().parent
# Dependency order; each may import only the ones before it.
_EMBED = ("errors.py", "wire.py", "auth.py", "http.py", "client.py")
TOOL_FILES = ("dt.py", "dt.sh", "validate_env.py", "verify.py", "adapter.py")

_ORIGINAL_CLIENT = """def client():
    from daytona import Daytona, DaytonaConfig
    key = os.environ.get("DAYTONA_API_KEY", "")
    if not key:
        raise SystemExit("dt: DAYTONA_API_KEY is not set")
    return Daytona(DaytonaConfig(api_key=key))
"""

_SILO_CLIENT = """def client():
    # silo: the provider is a silo broker, not Daytona. See the header.
    key = os.environ.get("SILO_API_TOKEN", "")
    if not key:
        raise SystemExit("dt: SILO_API_TOKEN is not set")
    direct = os.environ.get("SILO_BROKER_URL") or None
    resolve = os.environ.get("SILO_BROKER_RESOLVE_URL") or None
    if not direct and not resolve:
        raise SystemExit("dt: set SILO_BROKER_RESOLVE_URL (or SILO_BROKER_URL)")
    return _silo().SiloClient(direct, key, resolve_url=resolve)
"""

_ORIGINAL_BUDGET_LOOP = (
    "    while time.time() - t0 < quota_wait:\n        try:\n            mine, usage, quota = _counts()"
)
_DISABLED_BUDGET_LOOP = (
    "    # silo: there is no snapshot quota to wait for, so the budget wait never runs.\n"
    "    while False:\n        try:\n            mine, usage, quota = _counts()"
)

_MAIN_GUARD = '\nif __name__ == "__main__":'


def embedded_client_source() -> str:
    """The silo client modules as one stdlib-only source string."""
    parts = ["from __future__ import annotations\n"]
    for name in _EMBED:
        text = (_SILO / name).read_text()
        text = re.sub(r"(?m)^from __future__ import annotations\n", "", text)
        # Intra-package imports become no-ops: everything shares one namespace.
        text = re.sub(r"(?ms)^from silo\.[\w.]+ import \((?:[^)]*)\)\n", "", text)
        text = re.sub(r"(?m)^from silo\.[\w.]+ import [^\n]+\n", "", text)
        if "import silo" in text or "from silo" in text:
            raise RuntimeError(f"{name} still imports silo after flattening")
        parts.append(f"# ---- silo/{name} " + "-" * 40 + "\n" + text)
    return "\n".join(parts)


def _anchor(text: str, old: str, new: str, what: str) -> str:
    count = text.count(old)
    if count != 1:
        raise RuntimeError(f"dt.py anchor for {what} found {count} times (expected exactly 1); upstream dt.py changed")
    return text.replace(old, new)


def generate_dt(original: str) -> str:
    text = _anchor(original, _ORIGINAL_CLIENT, _SILO_CLIENT, "client()")
    text = _anchor(text, _ORIGINAL_BUDGET_LOOP, _DISABLED_BUDGET_LOOP, "the snapshot budget wait")
    if text.count(_MAIN_GUARD) != 1:
        raise RuntimeError("dt.py has no single __main__ guard to insert the embedded client before")
    source = embedded_client_source()
    embed = (
        "\n\n# " + "=" * 76 + "\n"
        "# silo: the embedded provider client (stdlib only). Generated by silo.dt_shim;\n"
        f"# embedded source sha256 {hashlib.sha256(source.encode()).hexdigest()}.\n"
        "_SILO_SOURCE = " + repr(source) + "\n"
        "_SILO_MODULE = None\n\n\n"
        "def _silo():\n"
        "    global _SILO_MODULE\n"
        "    if _SILO_MODULE is None:\n"
        "        import types\n"
        "        module = types.ModuleType('silo_embedded')\n"
        "        sys.modules['silo_embedded'] = module  # dataclasses resolve their module here\n"
        "        exec(compile(_SILO_SOURCE, 'silo_embedded', 'exec'), module.__dict__)  # noqa: S102\n"
        "        _SILO_MODULE = module\n"
        "    return _SILO_MODULE\n"
    )
    head, guard, tail = text.partition(_MAIN_GUARD)
    header = (
        "# GENERATED by silo.dt_shim from the maintained dt.py "
        f"(sha256 {hashlib.sha256(original.encode()).hexdigest()}).\n"
        "# Provider: silo (nested sandboxes in Iris jobs), not Daytona. CLI and JSON are unchanged.\n"
    )
    if head.startswith("#!"):
        shebang, _, rest = head.partition("\n")
        head = f"{shebang}\n{header}{rest}"
    else:
        head = header + head
    return head + embed + guard + tail


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tools-src", type=Path, required=True)
    parser.add_argument("--tools-out", type=Path, required=True)
    args = parser.parse_args(argv)
    args.tools_out.mkdir(parents=True, exist_ok=True)
    for name in TOOL_FILES:
        source = args.tools_src / name
        if not source.is_file():
            raise SystemExit(f"missing {source}")
        if name == "dt.py":
            (args.tools_out / name).write_text(generate_dt(source.read_text()))
        else:
            shutil.copy2(source, args.tools_out / name)
    out = args.tools_out / "dt.py"
    out.chmod(0o755)
    print(f"wrote {out} sha256={hashlib.sha256(out.read_bytes()).hexdigest()}")


if __name__ == "__main__":
    main()
