"""Corrected view of the single-phase heldout registry for the Delphi dose-response runs.

The 2026-09-03 export accepted complete W&B summaries for 57 preempted (``crashed``) dose-response runs whose
summaries froze at an earlier evaluation step. This script reads, for every non-finished run, the region-local
``eval_metrics.jsonl`` next to its checkpoints and takes the Uncheatable payload at the exact final step, validates
the components against the aggregate, writes the recovery table, and copies the registry with the affected run
values, coordinate means and component cells replaced. Rows, order and every other value are unchanged. The
canonical registry must still be regenerated by its materializer once that script prefers the persisted payload.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

import fsspec
import numpy as np
import pandas as pd

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parents[3]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from experiments.domain_phase_mix.exploratory.two_phase_many import (  # noqa: E402
    prepare_single_phase_heldout_benchmark_20260902 as heldout,
)

REFERENCE_OUTPUTS = SCRIPT_DIR / "reference_outputs"
CANONICAL_REGISTRY = REFERENCE_OUTPUTS / "single_phase_heldout_benchmark_20260902"
RAW_RESULTS = (
    REFERENCE_OUTPUTS
    / "bucket_epoch_dose_response_20260729"
    / "recovery"
    / "delphi_3e18_20260902"
    / "heldout_results.csv"
)
CHECKPOINT_ROOT = "gs://marin-us-east5/pinlin_calvin_xu/data_mixture/bed3_20260729"
FINAL_STEP = 3006
PANEL = "delphi_3e18_39bucket"
RECOVERY_NAME = "dose_uncheatable_final_step.csv"


def component_aggregate(values: np.ndarray) -> float:
    return float(values @ heldout.DELPHI_UNCHEATABLE_WEIGHTS)


def recover(results: pd.DataFrame) -> pd.DataFrame:
    """Exact final-step Uncheatable payloads for every run that W&B does not report as finished."""
    filesystem = fsspec.filesystem("gcs")
    rows = []
    for record in results[results["training_wandb_state"].ne("finished")].itertuples(index=False):
        uri = record.uncheatable_source_uri
        if not isinstance(uri, str) or not uri:
            uri = f"{CHECKPOINT_ROOT}/{record.training_wandb_run_id}/checkpoints/eval_metrics.jsonl"
        row = {
            "run_name": record.run_name,
            "run_id": record.training_wandb_run_id,
            "provenance": record.uncheatable_provenance,
            "current_U": record.uncheatable_bpb,
            "uri": uri,
        }
        if not filesystem.exists(uri):
            rows.append({**row, "status": "missing_file"})
            continue
        with filesystem.open(uri, "rt") as handle:
            payloads = [json.loads(line) for line in handle if line.strip()]
        final = [payload for payload in payloads if int(payload.get("step", -1)) == FINAL_STEP]
        if not final:
            rows.append({**row, "status": "no_final_step"})
            continue
        payload = final[-1]
        values = np.asarray([payload.get(key) for key in heldout.UNCHEATABLE_COMPONENTS], dtype=float)
        aggregate = payload.get(heldout.UNCHEATABLE_AGGREGATE)
        if aggregate is None or not np.isfinite(values).all():
            rows.append({**row, "status": "incomplete_payload"})
            continue
        if abs(component_aggregate(values) - float(aggregate)) > heldout.AGGREGATE_TOLERANCE:
            rows.append({**row, "status": "components_disagree"})
            continue
        row.update(
            {"status": "ok", "final_U": float(aggregate), "delta": float(aggregate) - float(record.uncheatable_bpb)}
        )
        row.update(dict(zip(heldout.UNCHEATABLE_COMPONENTS, values, strict=True)))
        rows.append(row)
    return pd.DataFrame(rows)


def corrected_view(source: Path, destination: Path, recovery: pd.DataFrame) -> dict[str, int]:
    fixed = recovery[recovery["status"].eq("ok") & recovery["delta"].abs().gt(1e-9)]
    aggregate_fix = dict(zip(fixed["run_id"], fixed["final_U"], strict=True))
    component_fix = {
        run_id: {
            key: float(fixed.loc[fixed["run_id"].eq(run_id), key].iloc[0]) for key in heldout.UNCHEATABLE_COMPONENTS
        }
        for run_id in fixed["run_id"]
    }
    runs = pd.read_csv(source / "heldout_runs.csv")
    affected = runs["training_wandb_run_id"].isin(aggregate_fix)
    runs.loc[affected, "uncheatable_bpb"] = runs.loc[affected, "training_wandb_run_id"].map(aggregate_fix)
    coordinates = pd.read_csv(source / "heldout_coordinates.csv")
    eligible = runs[runs["eligible"].astype(bool)]
    for coordinate_id in set(runs.loc[affected, "coordinate_id"]):
        values = eligible.loc[eligible["coordinate_id"].eq(coordinate_id), "uncheatable_bpb"].dropna()
        index = coordinates.index[coordinates["coordinate_id"].eq(coordinate_id)]
        if int(coordinates.loc[index, "uncheatable_n"].iloc[0]) != len(values):
            raise ValueError(f"{coordinate_id}: run count does not match the coordinate table")
        coordinates.loc[index, "uncheatable_mean_bpb"] = values.mean()
        coordinates.loc[index, "uncheatable_sd_bpb"] = values.std(ddof=1) if len(values) > 1 else np.nan
    components = pd.read_csv(source / "heldout_components.csv")
    coordinate_components = pd.read_csv(source / "heldout_coordinate_components.csv")
    row_by_run = dict(zip(runs["training_wandb_run_id"], runs["row_id"], strict=True))
    coordinate_by_row = dict(zip(runs["row_id"], runs["coordinate_id"], strict=True))
    cells = 0
    for run_id, values in component_fix.items():
        row_id = row_by_run.get(run_id)
        if row_id is None:
            continue
        for key, value in values.items():
            mask = components["row_id"].eq(row_id) & components["component"].eq(key)
            components.loc[mask, "bpb"] = value
            cells += int(mask.sum())
            coordinate_mask = coordinate_components["coordinate_id"].eq(
                coordinate_by_row[row_id]
            ) & coordinate_components["component"].eq(key)
            if coordinate_mask.any() and int(coordinate_components.loc[coordinate_mask, "run_count"].iloc[0]) != 1:
                raise ValueError(f"{row_id}: component cell with repeats cannot be replaced by a single run")
            coordinate_components.loc[coordinate_mask, "bpb_mean"] = value
    destination.mkdir(parents=True, exist_ok=True)
    runs.to_csv(destination / "heldout_runs.csv", index=False)
    coordinates.to_csv(destination / "heldout_coordinates.csv", index=False)
    components.to_csv(destination / "heldout_components.csv", index=False)
    coordinate_components.to_csv(destination / "heldout_coordinate_components.csv", index=False)
    for name in (
        "mixture_weights.csv",
        "source_inventory.csv",
        "target_coverage.csv",
        "excluded_rows.csv",
        "component_reconstruction.csv",
    ):
        if (source / name).is_file():
            shutil.copy(source / name, destination / name)
    manifest = json.loads((source / "manifest.json").read_text())
    manifest["round3_correction"] = {
        "runs_corrected": len(fixed),
        "registry_runs_replaced": int(affected.sum()),
        "component_cells_replaced": cells,
        "recovery_table": RECOVERY_NAME,
        "source_registry_manifest_sha256": hashlib.sha256((source / "manifest.json").read_bytes()).hexdigest(),
    }
    (destination / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return {
        "runs_corrected": len(fixed),
        "registry_runs_replaced": int(affected.sum()),
        "component_cells_replaced": cells,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry-dir", type=Path, default=CANONICAL_REGISTRY)
    parser.add_argument("--raw-results", type=Path, default=RAW_RESULTS)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument(
        "--recovery-table", type=Path, default=None, help="reuse an existing recovery table instead of reading GCS"
    )
    args = parser.parse_args()
    if args.recovery_table is not None:
        recovery = pd.read_csv(args.recovery_table)
    else:
        recovery = recover(pd.read_csv(args.raw_results))
    args.output_dir.mkdir(parents=True, exist_ok=True)
    recovery.to_csv(args.output_dir / RECOVERY_NAME, index=False)
    print("recovery status:", recovery["status"].value_counts().to_dict())
    ok = recovery[recovery["status"].eq("ok")]
    print("delta (final - exported) by provenance:")
    print(ok.groupby("provenance")["delta"].describe()[["count", "mean", "min", "50%", "max"]].round(5).to_string())
    print("runs shifted by more than 0.01:", int((ok["delta"].abs() > 0.01).sum()))
    counts = corrected_view(args.registry_dir, args.output_dir, recovery)
    (args.output_dir / "README.md").write_text(
        "Temporary corrected view of single_phase_heldout_benchmark_20260902 (round 3, 2026-09-03): "
        "Uncheatable values of\n"
        f"{counts['runs_corrected']} preempted dose-response runs replaced by their exact step-{FINAL_STEP} payloads "
        f"({counts['registry_runs_replaced']} registry rows, {counts['component_cells_replaced']} component cells).\n"
        "Regenerate the canonical registry instead of using this copy once the materializer prefers "
        "persisted payloads.\n"
    )
    print(counts)


if __name__ == "__main__":
    main()
