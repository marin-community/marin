def main() -> None:
    registry = pd.read_csv(REGISTRY)
    row = registry_row()
    registry = registry.loc[~registry["id"].eq(row["id"])]
    registry = pd.concat([registry, pd.DataFrame([row], columns=registry.columns)], ignore_index=True)
    registry.to_csv(REGISTRY, index=False)

    ledger = pd.read_csv(LEDGER)
    ledger_row = {
        "timestamp": datetime.now(UTC).isoformat(),
        "round_id": "round_38_muon_polar_matrix",
        "candidate_id": row["id"],
        "candidate_family": row["family"],
        "hyperparameters": row["status_evidence"].split("Frozen grid: ", maxsplit=1)[1],
        "adversarial_outcomes_available_before_proposal": True,
        "adversarial_outcomes_inspected_before_proposal": True,
        "observations_inspiring_mechanism": "Source audit after CTPF and SPTF found that MuonH also applies a matrix zeroth-power map. The exposed development failures were already known; no new adversarial row was inspected.",
        "novelty_class": "Matrix singular-direction equalization in the state transition",
        "evaluation_status": "preregistered before StarCoder evaluation",
        "evidence_path": "round38_muon_polar_matrix_starcoder/report.md",
        "notes": "The running frontier phase-fiber panel remains sealed and absent from all inputs.",
    }
    identity = ["round_id", "candidate_id", "evaluation_status"]
    existing = set(map(tuple, ledger[identity].itertuples(index=False, name=None)))
    key = tuple(ledger_row[column] for column in identity)
    if key not in existing:
        ledger = pd.concat([ledger, pd.DataFrame([ledger_row], columns=ledger.columns)], ignore_index=True)
        ledger.to_csv(LEDGER, index=False)


if __name__ == "__main__":
    main()
