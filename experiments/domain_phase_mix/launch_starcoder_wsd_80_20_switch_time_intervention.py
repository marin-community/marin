WANDB_EXPERIMENT_TAG = "starcoder_wsd80_switch_time_intervention_2b_20260731"
DEFAULT_MAX_CONCURRENT = 82
EVAL_INTERVAL_STEPS = 40
EXPERIMENT_BUDGET = 2_000_000_000

DESIGN_DIR = (
    Path(__file__).parent
    / "exploratory"
    / "two_phase_many"
    / "reference_outputs"
    / "switch_time_intervention_design_20260731"
)
MANIFEST_PATH = DESIGN_DIR / "manifest.csv"
PROTOCOL_PATH = DESIGN_DIR / "protocol.json"
DESIGN_SCRIPT_PATH = (
    Path(__file__).parent / "exploratory" / "two_phase_many" / "design_switch_time_intervention_20260731.py"
)
EVALUATOR_PATH = (
    Path(__file__).parent / "exploratory" / "two_phase_many" / "evaluate_switch_time_intervention_20260731.py"
)


@dataclass(frozen=True)
class InterventionRunSpec:
    """One observation in the frozen switch-time intervention manifest."""

    observation_id: str
    coordinate_id: str
    phase_0_starcoder: float
    phase_1_starcoder: float
    switch_step: int
    run_seed: int
    simulated_epoch_subset_seed: int

    @property
    def run_name(self) -> str:
        return self.observation_id


def canonical_json_bytes(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()


def sha256_json(value: Any) -> str:
    return hashlib.sha256(canonical_json_bytes(value)).hexdigest()


def sha256_path(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_run_specs() -> tuple[InterventionRunSpec, ...]:
    """Load and verify the frozen observation manifest and launcher source."""
    protocol = json.loads(PROTOCOL_PATH.read_text())
    claimed_protocol_hash = str(protocol.pop("protocol_sha256"))
    observed_protocol_hash = sha256_json(protocol)
    if observed_protocol_hash != claimed_protocol_hash:
        raise ValueError(f"Switch-time protocol self-hash mismatch: {observed_protocol_hash} != {claimed_protocol_hash}")
    protocol["protocol_sha256"] = claimed_protocol_hash
    with MANIFEST_PATH.open(newline="") as handle:
        rows = list(csv.DictReader(handle))

    expected_manifest_hash = protocol["panel"]["manifest_sha256"]
    if sha256_json(rows) != expected_manifest_hash:
        raise ValueError("Switch-time manifest does not match the frozen protocol")
    expected_launcher_hash = protocol["sources"]["launcher_sha256"]
    if sha256_path(Path(__file__)) != expected_launcher_hash:
        raise ValueError("Switch-time launcher source does not match the frozen protocol")
    expected_base_hash = protocol["sources"]["canonical_wsd80_launcher_sha256"]
    if sha256_path(Path(wsd80.__file__)) != expected_base_hash:
        raise ValueError("Canonical WSD80 launcher source does not match the frozen protocol")
    expected_design_hash = protocol["sources"]["design_script_sha256"]
    if sha256_path(DESIGN_SCRIPT_PATH) != expected_design_hash:
        raise ValueError("Switch-time design source does not match the frozen protocol")
    expected_evaluator_hash = protocol["sources"]["evaluator_sha256"]
    if sha256_path(EVALUATOR_PATH) != expected_evaluator_hash:
        raise ValueError("Switch-time evaluator source does not match the frozen protocol")

    schedule = wsd80._schedule_summary(EXPERIMENT_BUDGET)
    protocol_schedule = protocol["schedule"]
    schedule_checks = {
        "total_steps": int(schedule["total_steps"]),
        "boundary_step": int(schedule["boundary_step"]),
        "warmup_steps": int(schedule["warmup_steps"]),
        "decay_steps": int(schedule["decay_steps"]),
        "materialized_tokens": int(schedule["materialized_tokens"]),
    }
    for key, observed in schedule_checks.items():
        if observed != int(protocol_schedule[key]):
            raise ValueError(f"Canonical WSD80 schedule drifted at {key}: {observed} != {protocol_schedule[key]}")
    if EVAL_INTERVAL_STEPS != int(protocol_schedule["eval_interval_steps"]):
        raise ValueError("Evaluation cadence does not match the frozen protocol")

    expected_observations = int(protocol["panel"]["observations"])
    if len(rows) != expected_observations:
        raise ValueError(f"Expected {expected_observations} manifest rows, found {len(rows)}")
    coordinate_ids = {row["coordinate_id"] for row in rows}
    expected_coordinates = int(protocol["panel"]["unique_coordinates"])
    if len(coordinate_ids) != expected_coordinates:
        raise ValueError(f"Expected {expected_coordinates} coordinates, found {len(coordinate_ids)}")
    expected_switches = {int(step) for step in protocol_schedule["data_switch_steps"]}
    if {int(row["switch_step"]) for row in rows} != expected_switches:
        raise ValueError("Manifest switch ladder does not match the frozen protocol")
    if str(protocol["panel"]["simulated_epoch_subset_seed_policy"]) != "equals_run_seed":
        raise ValueError("Unknown simulated-epoch subset-seed policy")
    if any(int(row["simulated_epoch_subset_seed"]) != int(row["run_seed"]) for row in rows):
        raise ValueError("Manifest subset seed must equal the run seed")
    expected_run_seeds = {
        int(seed) for key in ("asymmetric_seed_values", "spine_seed_values") for seed in protocol["panel"][key]
    }
    if not {int(row["run_seed"]) for row in rows}.issubset(expected_run_seeds):
        raise ValueError("Manifest contains a run seed outside the frozen seed block")

    specs = tuple(
        InterventionRunSpec(
            observation_id=row["observation_id"],
            coordinate_id=row["coordinate_id"],
            phase_0_starcoder=float(row["phase_0_code_weight"]),
            phase_1_starcoder=float(row["phase_1_code_weight"]),
            switch_step=int(row["switch_step"]),
            run_seed=int(row["run_seed"]),
            simulated_epoch_subset_seed=int(row["simulated_epoch_subset_seed"]),
        )
        for row in rows
    )
    if len({spec.observation_id for spec in specs}) != len(specs):
        raise ValueError("Observation IDs must be unique")
    return specs


def selected_validation_datasets() -> tuple[ArtifactStep[TokenizedCache], ...]:
    """Return only the five smooth targets frozen for transition identification."""
    paloma = paloma_datasets(tokenizer=llama3_tokenizer)
    uncheatable = uncheatable_datasets(tokenizer=llama3_tokenizer)
    return (
        paloma["dolma_100_programing_languages"],
        uncheatable["github_python"],
        uncheatable["github_cpp"],
        paloma["c4_en"],
        paloma["falcon-refinedweb"],
    )


def with_switch_time_mixture(
    base: ArtifactStep[LevanterCheckpoint],
    *,
    train_datasets: dict[ArtifactStep[TokenizedCache], float],
    validation_datasets: tuple[ArtifactStep[TokenizedCache], ...],
    phase_weights: list[tuple[int, dict[str, float]]],
    run_seed: int,
    simulated_epoch_subset_seed: int,
) -> ArtifactStep[LevanterCheckpoint]:
    """Replace a static training handle with the frozen switch-time schedule."""
    schedule = wsd80._schedule_summary(EXPERIMENT_BUDGET)
    materialized_tokens = int(schedule["materialized_tokens"])

    def build_config(ctx: StepContext) -> TrainLmOnPodConfig:
        pod_config = base.build_config(ctx)
        data_config = mixture(ctx, train_datasets, validation=validation_datasets)
        data_config = replace(
            data_config,
            train_weights=phase_weights,
            mixture_block_size=wsd80.MIXTURE_BLOCK_SIZE,
            experiment_budget=materialized_tokens,
            target_budget=wsd80.TARGET_BUDGET,
            simulated_epoch_subset_seed=simulated_epoch_subset_seed,
        )
        trainer = replace(pod_config.train_config.trainer, seed=run_seed)
        train_config = replace(
            pod_config.train_config,
            data=data_config,
            data_seed=run_seed,
            trainer=trainer,
        )
        return replace(pod_config, train_config=train_config)

    return replace(base, build_config=build_config)


def build_training_steps(
    *,
    name_prefix: str,
    tpu_type: str,
    tpu_region: str,
    tpu_zone: str,
) -> tuple[ArtifactStep[LevanterCheckpoint], ...]:
    """Build resumable handles for every frozen manifest observation."""
    specs = load_run_specs()
    nemotron = nemotron_datasets(tokenizer=llama3_tokenizer)
    starcoder = dolma_datasets(tokenizer=llama3_tokenizer)["dolma/starcoder"]
    training_handles = (*tuple(nemotron[split] for split in wsd80.NEMOTRON_TOKEN_COUNTS), starcoder)
    validation_handles = selected_validation_datasets()
    protocol = json.loads(PROTOCOL_PATH.read_text())
    target_metrics = (
        protocol["targets"]["primary"],
        *protocol["targets"]["code_transfer"],
        *protocol["targets"]["broad_text_negative_controls"],
    )
    expected_validation_names = tuple(metric.removeprefix("eval/").removesuffix("/bpb") for metric in target_metrics)
    observed_validation_names = tuple(handle.name for handle in validation_handles)
    if observed_validation_names != expected_validation_names:
        raise ValueError(
            "Validation handles do not match the frozen target order: "
            f"{observed_validation_names!r} != {expected_validation_names!r}"
        )
    resources = ResourceConfig.with_tpu(tpu_type, regions=(tpu_region,), zone=tpu_zone)
    schedule = wsd80._schedule_summary(EXPERIMENT_BUDGET)
    optimizer = wsd80._optimizer(EXPERIMENT_BUDGET)
    if optimizer.warmup != schedule["warmup_steps"] or optimizer.decay != schedule["decay_steps"]:
        raise ValueError("Canonical optimizer schedule changed")

    steps: list[ArtifactStep[LevanterCheckpoint]] = []
    for spec in specs:
        phase_0_weights = wsd80._phase_leaf_weights(
            spec.phase_0_starcoder,
            nemotron=nemotron,
            starcoder=starcoder,
        )
        phase_1_weights = wsd80._phase_leaf_weights(
            spec.phase_1_starcoder,
            nemotron=nemotron,
            starcoder=starcoder,
        )
        static_weights = {handle: phase_0_weights[handle.name] for handle in training_handles}
        base = train_lm(
            name=f"checkpoints/{name_prefix}/{spec.run_name}",
            version=VERSION,
            model=wsd80.REGMIX_60M_PROXY,
            optimizer=optimizer,
            datasets=static_weights,
            validation=validation_handles,
            batch_size=wsd80.BATCH_SIZE,
            seq_len=wsd80.SEQ_LEN,
            num_train_steps=int(schedule["total_steps"]),
            z_loss_weight=None,
            evals=None,
            resources=resources,
            steps_per_eval=EVAL_INTERVAL_STEPS,
            wandb_project="marin",
            wandb_group=name_prefix,
            run_id=spec.run_name,
            tags=(
                WANDB_EXPERIMENT_TAG,
                spec.observation_id,
                spec.coordinate_id,
                "starcoder",
                "wsd80_20",
                "switch_time_intervention",
            ),
            env_vars={"HF_ALLOW_CODE_EVAL": "1"},
        )
        steps.append(
            with_switch_time_mixture(
                base,
                train_datasets=static_weights,
                validation_datasets=validation_handles,
                phase_weights=[
                    (0, phase_0_weights),
                    (spec.switch_step, phase_1_weights),
                ],
                run_seed=spec.run_seed,
                simulated_epoch_subset_seed=spec.simulated_epoch_subset_seed,
            )
        )
    return tuple(steps)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--name-prefix", default=NAME)
    parser.add_argument("--marin-prefix", default=wsd80.DEFAULT_MARIN_PREFIX)
    parser.add_argument("--tpu-type", default=wsd80.DEFAULT_TPU_TYPE)
    parser.add_argument("--tpu-region", default=wsd80.DEFAULT_TPU_REGION)
    parser.add_argument("--tpu-zone", default=wsd80.DEFAULT_TPU_ZONE)
    parser.add_argument("--max-concurrent", type=int, default=DEFAULT_MAX_CONCURRENT)
    parser.add_argument("--dry-run", action="store_true")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if os.getenv("CI") is not None:
        logger.info("Skipping StarCoder switch-time intervention in CI")
        return
    if args.marin_prefix != wsd80.DEFAULT_MARIN_PREFIX:
        raise ValueError(f"Historical StarCoder work must remain central1-local: {args.marin_prefix!r}")
    if args.tpu_region != wsd80.DEFAULT_TPU_REGION or args.tpu_zone != wsd80.DEFAULT_TPU_ZONE:
        raise ValueError(
            "StarCoder child placement must remain central1-local: "
            f"region={args.tpu_region!r}, zone={args.tpu_zone!r}"
        )

    specs = load_run_specs()
    if not 1 <= args.max_concurrent <= len(specs):
        raise ValueError(f"max_concurrent must be in [1, {len(specs)}], got {args.max_concurrent}")

    os.environ["MARIN_PREFIX"] = args.marin_prefix
    steps = build_training_steps(
        name_prefix=args.name_prefix,
        tpu_type=args.tpu_type,
        tpu_region=args.tpu_region,
        tpu_zone=args.tpu_zone,
    )
    if args.dry_run:
        for step in steps:
            lower(step)
        logger.info("Dry-run lowering passed for all %d training handles", len(steps))
        return

    run(*steps, max_concurrent=args.max_concurrent)


if __name__ == "__main__":
    main()
