"""Build the preregistered WSD80 switch-time intervention panel.

The panel varies the data-mixture switch while preserving the canonical
optimizer schedule. Its frozen manifest is generated by
``design_switch_time_intervention_20260731.py``. This launcher does not submit
unless invoked without ``--dry-run`` by an explicitly approved parent job.
"""

