"""Replay recorded ``joint_decode_avg_xtok`` rollouts for advisor-drift scoring.

A finished eval step persists, per completion, the step-aligned committed byte
chunks and each side's exact forced token ids (the ``token_paths.jsonl.gz``
sidecar). This module loads selected completions into ``Rollout`` records and
derives the per-boundary byte prefixes that ``scoring`` conditions on. See
``.agents/projects/20260715_xtok_advisor_drift_viz_plan.md``.
"""

from __future__ import annotations

import json
import os
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any

import fsspec

from experiments.downstream_scaling.evals.algorithms import xtok_selection
from experiments.downstream_scaling.evals.framework.schema import (
    COMPLETIONS_FILENAME,
    PROMPTS_FILENAME,
    completions_file,
    prompts_file,
    read_completion_rows,
    read_prompt_rows,
)

# Mirrors algorithms.joint_decode_avg_xtok.TOKEN_PATHS_FILENAME. Not imported:
# that module pulls fray/zephyr/thalas, which the tool's minimal GPU venv does
# not install.
TOKEN_PATHS_FILENAME = "token_paths.jsonl.gz"


@dataclass(frozen=True)
class Step:
    """One committed decision round: the chunk's bytes and each side's exact
    forced token ids, as recorded by the pipeline."""

    chunk: bytes
    tokens_a: tuple[int, ...]
    tokens_b: tuple[int, ...]


@dataclass(frozen=True)
class Rollout:
    problem_id: str
    completion_index: int
    advisor_weight: float
    prompt: str
    # Non-EOS steps only; a trailing selector-chosen EOS step (empty bytes) is
    # recorded in ended_with_eos instead.
    steps: tuple[Step, ...]
    ended_with_eos: bool


@dataclass(frozen=True)
class BoundaryPrefix:
    """A chunk boundary whose byte prefix decodes as UTF-8: after 1-based step
    ``step_index``, the generated bytes so far spell ``text``."""

    step_index: int
    byte_offset: int
    text: str


def generated_bytes(rollout: Rollout) -> bytes:
    return b"".join(step.chunk for step in rollout.steps)


def decoded_boundaries(rollout: Rollout) -> tuple[list[BoundaryPrefix], list[int]]:
    """Boundary prefixes for every step, plus byte offsets of skipped
    boundaries (prefixes ending mid-codepoint, which cannot be re-encoded)."""
    valid: list[BoundaryPrefix] = []
    skipped: list[int] = []
    data = bytearray()
    for step_index, step in enumerate(rollout.steps, start=1):
        data.extend(step.chunk)
        try:
            text = bytes(data).decode("utf-8")
        except UnicodeDecodeError:
            skipped.append(len(data))
            continue
        valid.append(BoundaryPrefix(step_index=step_index, byte_offset=len(data), text=text))
    return valid, skipped


def verify_token_paths(rollout: Rollout, vocab_b: xtok_selection.Vocab) -> None:
    """Check the replay identity: the advisor's recorded forced ids for every
    chunk equal greedy segmentation of the chunk's bytes (``force`` reduces to
    ``segment`` because byte strings are unique per vocab; see the plan doc).
    A mismatch means our replay model of the pipeline is wrong and any scoring
    built on it would be meaningless."""
    for step_index, step in enumerate(rollout.steps, start=1):
        expected = xtok_selection.segment(vocab_b, step.chunk)
        if list(step.tokens_b) != expected:
            raise ValueError(
                f"{rollout.problem_id} completion {rollout.completion_index} step {step_index}: "
                f"recorded tokens_b {list(step.tokens_b)} != segment(chunk bytes) {expected}"
            )


def _parse_steps(record: dict[str, Any], *, context: str) -> tuple[tuple[Step, ...], bool]:
    steps: list[Step] = []
    raw_steps = record["steps"]
    for position, raw in enumerate(raw_steps):
        chunk = bytes.fromhex(raw["bytes_hex"])
        if not chunk:
            # Empty bytes <=> selector-chosen EOS (see _path_step in
            # joint_decode_avg_xtok); it carries no scoring information and
            # must be terminal.
            if position != len(raw_steps) - 1:
                raise ValueError(f"{context}: empty-bytes step at position {position} is not terminal")
            return tuple(steps), True
        steps.append(Step(chunk=chunk, tokens_a=tuple(raw["tokens_a"]), tokens_b=tuple(raw["tokens_b"])))
    return tuple(steps), False


def _localize(step_dir: str, cache_dir: str, filenames: tuple[str, ...]) -> str:
    """Mirror a remote step dir's eval files under the input cache, once.

    Step basenames carry the executor version hash and hashed step outputs are
    immutable, so cached copies never go stale and need no invalidation."""
    if "://" not in step_dir:
        return step_dir
    local_dir = os.path.join(cache_dir, "inputs", os.path.basename(step_dir.rstrip("/")))
    os.makedirs(local_dir, exist_ok=True)
    for filename in filenames:
        local_path = os.path.join(local_dir, filename)
        if os.path.exists(local_path):
            continue
        fs, remote_path = fsspec.url_to_fs(f"{step_dir.rstrip('/')}/{filename}")
        # Per-process temp name: concurrent jobs sharing a cache must not
        # interleave writes into one file; the rename keeps a killed download
        # from ever poisoning the cache.
        partial_path = f"{local_path}.partial.{os.getpid()}"
        fs.get_file(remote_path, partial_path)
        os.replace(partial_path, local_path)
    return local_dir


def load_rollouts(
    completions_output: str,
    *,
    prompts_output: str,
    advisor_weights: Sequence[float],
    sample_ranks: Sequence[int],
    problem_ids: Sequence[str] | None = None,
    limit: int | None = None,
    cache_dir: str | None = None,
) -> list[Rollout]:
    """Load selected completions from a finished eval sweep.

    ``completions_output`` is the completions step dir (holds
    ``completions.jsonl.gz`` and ``token_paths.jsonl.gz``); ``prompts_output``
    is the task's prompts step dir; both accept ``gs://`` or local paths.
    ``sample_ranks`` selects within each (problem, weight) group by rank of
    ``completion_index``; ``problem_ids`` of None means every problem;
    ``limit`` truncates the problem-ordered selection to its first N rollouts.
    With ``cache_dir``, remote inputs are downloaded once under
    ``<cache_dir>/inputs/`` and reruns read the local copies.
    """
    if limit is not None and limit < 1:
        raise ValueError(f"limit must be >= 1 or None (got {limit})")
    if cache_dir is not None:
        completions_output = _localize(completions_output, cache_dir, (TOKEN_PATHS_FILENAME, COMPLETIONS_FILENAME))
        prompts_output = _localize(prompts_output, cache_dir, (PROMPTS_FILENAME,))
    wanted_ids = None if problem_ids is None else set(problem_ids)
    wanted_weights = set(advisor_weights)

    prompts: dict[str, str] = {}
    for prompt_row in read_prompt_rows(prompts_file(prompts_output)):
        if wanted_ids is None or prompt_row["id"] in wanted_ids:
            prompts[prompt_row["id"]] = prompt_row["prompt"]
    if wanted_ids is not None:
        missing = wanted_ids - prompts.keys()
        if missing:
            raise ValueError(f"prompt ids not found in {prompts_file(prompts_output)}: {sorted(missing)}")

    groups: dict[tuple[str, float], list[dict[str, Any]]] = {}
    with fsspec.open(os.path.join(completions_output, TOKEN_PATHS_FILENAME), "rt", compression="infer") as f:
        for line in f:
            record = json.loads(line)
            if record["advisor_weight"] not in wanted_weights:
                continue
            if wanted_ids is not None and record["id"] not in wanted_ids:
                continue
            groups.setdefault((record["id"], record["advisor_weight"]), []).append(record)

    selection_ids = sorted(wanted_ids) if wanted_ids is not None else sorted({key[0] for key in groups})
    if not selection_ids:
        raise ValueError(f"no token paths at weights {sorted(wanted_weights)} in {completions_output}")
    selected: list[dict[str, Any]] = []
    for problem_id in selection_ids:
        for weight in sorted(wanted_weights):
            group = groups.get((problem_id, weight))
            if not group:
                raise ValueError(f"no token paths for problem {problem_id!r} at advisor weight {weight}")
            group.sort(key=lambda record: record["completion_index"])
            for rank in sample_ranks:
                if rank >= len(group):
                    raise ValueError(
                        f"sample rank {rank} out of range: {len(group)} samples for {problem_id!r} at weight {weight}"
                    )
                selected.append(group[rank])
    if limit is not None:
        selected = selected[:limit]

    selected_ids = {record["id"] for record in selected}
    completion_lists: dict[str, list[dict[str, Any]]] = {}
    for completion_row in read_completion_rows(completions_file(completions_output)):
        if completion_row["id"] in selected_ids:
            completion_lists[completion_row["id"]] = completion_row["completions"]

    rollouts: list[Rollout] = []
    for record in selected:
        problem_id, weight = record["id"], record["advisor_weight"]
        context = f"{problem_id} completion {record['completion_index']}"
        if problem_id not in prompts:
            raise ValueError(f"{context}: id missing from {prompts_file(prompts_output)}")
        steps, ended_with_eos = _parse_steps(record, context=context)
        if not steps:
            raise ValueError(f"{context}: empty rollout (no committed chunks); pick another sample")
        completion = completion_lists[problem_id][record["completion_index"]]
        recorded_weight = completion["metadata"]["advisor_weight"]
        if recorded_weight != weight:
            raise ValueError(f"{context}: completions file weight {recorded_weight} != sidecar weight {weight}")
        # The completion text may be a strict prefix of the committed bytes:
        # vLLM trims text at stop strings, but the final round's tokens were
        # committed (and forced on the advisor) in full.
        joined = b"".join(step.chunk for step in steps)
        if not joined.startswith(completion["text"].encode("utf-8")):
            raise ValueError(f"{context}: committed bytes do not extend the completion text")
        rollouts.append(
            Rollout(
                problem_id=problem_id,
                completion_index=record["completion_index"],
                advisor_weight=weight,
                prompt=prompts[problem_id],
                steps=steps,
                ended_with_eos=ended_with_eos,
            )
        )
    return rollouts


PROMPTS_STEP_NAME = "downstream_scaling/evals/prompts/gsm8k"


# The bucket the sweep ran under. Deliberately not marin_prefix(): that
# resolves from the local cluster config and silently yields e.g. /tmp/marin
# on an unconfigured box, while this tool always probes the production run.
DEFAULT_EXECUTOR_PREFIX = "gs://marin-us-central2"


def resolve_step_paths(slug: str, *, prefix: str = DEFAULT_EXECUTOR_PREFIX) -> tuple[str, str]:
    """Resolve the GSM8K sweep's concrete (completions, prompts) step dirs for
    one Delphi slug by rebuilding the runner's step graph and computing
    versioned output paths — offline, nothing launched, no GCS I/O.

    Worker-pool arguments are plain (unversioned) fields of the completions
    step config, so placeholder pools resolve the same hashes as the
    production run.
    """
    # Local imports: this path pulls the runner's full orchestration stack,
    # which a venv passing --step-output/--prompts explicitly does not need.
    from fray.cluster import ANY_REGION  # noqa: PLC0415  # optional dep: orchestration stack
    from thalas.execution.context import executor_context  # noqa: PLC0415  # optional dep: orchestration stack
    from thalas.execution.executor import Executor  # noqa: PLC0415  # optional dep: orchestration stack

    from experiments.downstream_scaling.evals import (  # noqa: PLC0415  # optional dep: orchestration stack
        run_delphi_gsm8k_joint_decode_avg_xtok as sweep,
    )

    pools = sweep.make_worker_pools(
        tpu_types=list(sweep.TPU_TYPES),
        worker_regions=[ANY_REGION],
        num_workers=sweep.WORKERS_PER_TPU_TYPE,
    )
    steps = sweep.build_run_steps(pools)
    executor = Executor(prefix=prefix, executor_info_base_path=os.path.join(prefix, "experiments"))
    with executor_context():
        for step in steps:
            executor.compute_version(step, is_pseudo_dep=False)

    # build_run_steps constructs one prompts-step object per slug; same
    # name+version means they all resolve to the same path, so dedupe by path.
    completions_paths = {
        path for step, path in executor.output_paths.items() if step.name.endswith(f"/{slug}/completions")
    }
    prompts_paths = {path for step, path in executor.output_paths.items() if step.name == PROMPTS_STEP_NAME}
    if len(completions_paths) != 1:
        known = sorted(
            {step.name.rsplit("/", 2)[-2] for step in executor.output_paths if step.name.endswith("/completions")}
        )
        raise ValueError(f"slug {slug!r} matched {len(completions_paths)} completions paths; known slugs: {known}")
    if len(prompts_paths) != 1:
        raise ValueError(f"expected one {PROMPTS_STEP_NAME!r} path, found {sorted(prompts_paths)}")
    return next(iter(completions_paths)), next(iter(prompts_paths))
