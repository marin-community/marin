"""Keep activity identities stable across rebuilt MarinMirror corpora."""

import sqlalchemy


def upgrade(conn: sqlalchemy.Connection) -> None:
    conn.execute(sqlalchemy.text("SET LOCAL lock_timeout = '5s'"))
    conn.execute(sqlalchemy.text("ALTER TABLE chunks ADD COLUMN sync_hash TEXT"))
    conn.execute(sqlalchemy.text("ALTER TABLE chunks ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"))
    conn.execute(
        sqlalchemy.text(
            "SELECT setval(pg_get_serial_sequence('chunks', 'id'), "
            "COALESCE((SELECT max(id) FROM chunks), 0) + 1, false)"
        )
    )
    # Comparing only the embedding hash at a recycled corpus row number could leave
    # duplicate comments behind when two comments had identical embedding input.
    conn.execute(
        sqlalchemy.text(
            "DELETE FROM chunks c USING ("
            "SELECT id, row_number() OVER (PARTITION BY source, kind, url, part ORDER BY id) AS position "
            "FROM chunks) duplicates WHERE c.id = duplicates.id AND duplicates.position > 1"
        )
    )
    conn.execute(sqlalchemy.text("ALTER TABLE chunks ADD CONSTRAINT chunks_identity UNIQUE (source, kind, url, part)"))
    for table in ("chunks", "repository_file_chunks"):
        conn.execute(sqlalchemy.text(f"ALTER TABLE {table} SET (autovacuum_vacuum_scale_factor = 0.05)"))
