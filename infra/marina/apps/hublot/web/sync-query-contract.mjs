import { readFileSync, writeFileSync } from 'node:fs';
import {
  BACKGROUND_READ_PAUSE_MS, FLEET_CARD, inferenceTabGroups, MAX_OVERVIEW_DAYS, metricCards,
  METRIC_POINTS, metricSignals, MIN_WINDOW_MS, RAW_METRIC_WINDOW_MS, SAMPLE_BATCH_SIZE, SAMPLE_SLICE_MS, signals,
  SPAN_LOOKAHEAD_MS,
} from './src/contracts.js';
import { BUCKET_MS, MAX_COUNTER_GAP_MS, MIN_SUMMARY_BUCKET_MS } from './src/measurements.js';
import { driverLinePatterns, driverPhaseMarkers, driverTimestamp } from './src/phases.js';

// Keep the backend's fixed predicates in step with the signals used by the browser.
const literal = (value) => "'" + value.replaceAll("'", "''") + "'";
const predicate = ({ name, countName, filter, metricPattern }) => {
  const names = countName ? 'name IN (' + [name, countName].map(literal).join(', ') + ')' : 'name = ' + literal(name);
  const terms = [names, ...Object.entries(filter).map(([key, value]) =>
    'json_get(attributes_json, ' + literal(key) + ') = ' + literal(value))];
  if (metricPattern) terms.push("regexp_like(json_get(attributes_json, 'metric'), " + literal(metricPattern) + ')');
  return '(' + terms.join(' AND ') + ')';
};
const dispatch = [signals.slotWait, signals.promptWait];
const overviewEvents = ['async_phase_window', 'rollout_call', 'rollout_groups', 'weight_sync_completed'];
const readSeparately = new Set([...overviewEvents, 'async_run_configuration']);
const regular = Object.values(signals)
  .filter((s) => s.name && !readSeparately.has(s.name) && !dispatch.includes(s));
const overview = regular.filter((s) => s.filter.metric_source !== 'vllm');
const details = [FLEET_CARD, ...Object.keys(inferenceTabGroups), ...metricCards]
  .map((id) => [id, metricSignals(id).map(([, signal]) => signal)]);
const markers = driverPhaseMarkers.map(({ caller, message }) => {
  const text = 'contains(data, ' + literal(message) + ')';
  return caller ? '(contains(data, ' + literal(caller) + ') AND ' + text + ')' : text;
});

const fields = Object.values(signals);
const counters = fields.filter((s) => s.transform === 'cumulative' || s.transform === 'cumulativeMean')
  .flatMap(({ name, countName }) => countName ? [name, countName] : [name]);
const attributes = new Set(['step', 'reason', 'outcome', 'disposition', 'engine', 'engine_index', 'payload_kind', 'tool_backend', 'task_family']);
const body = new Set(['started_unix_ms', 'finished_unix_ms', 'duration_seconds', 'reason']);
for (const { filter, dimension, time, value, metricPattern } of fields) {
  for (const key of Object.keys(filter)) attributes.add(key);
  if (dimension) attributes.add(dimension);
  if (metricPattern) attributes.add('metric');
  for (const path of [time, value]) if (path?.startsWith('body_json.')) body.add(path.slice('body_json.'.length));
}

function sql(terms) {
  const fragments = terms.flatMap((term, index) => {
    const [first, ...rest] = term.split(' AND ');
    return [index ? ' OR ' + first : first, ...rest.map((part) => ' AND ' + part)];
  });
  return '(\n' + fragments.map((part) => '    ' + JSON.stringify(part)).join('\n') + '\n)';
}
function tuple(values) {
  const items = [...values].sort().map((value) => {
    const parts = JSON.stringify(value).length > 115 ? [value.slice(0, 80), value.slice(80)] : [value];
    return parts.map((part) => '    ' + JSON.stringify(part)).join('\n') + ',';
  });
  return '(\n' + items.join('\n') + '\n)';
}
const output = `# Copyright The Marin Authors
# SPDX-License-Identifier: Apache-2.0

"""Generated by npm run sync-query-contract in web/."""

MAX_OVERVIEW_MS = ${MAX_OVERVIEW_DAYS * 86_400_000}
MIN_WINDOW_MS = ${MIN_WINDOW_MS}
BUCKET_MS = ${BUCKET_MS}
COUNTER_MARGIN_MS = ${MAX_COUNTER_GAP_MS}
MIN_SUMMARY_BUCKET_MS = ${MIN_SUMMARY_BUCKET_MS}
RAW_METRIC_WINDOW_MS = ${RAW_METRIC_WINDOW_MS}
METRIC_POINTS = ${METRIC_POINTS}
FLEET_CARD = ${JSON.stringify(FLEET_CARD)}
INFERENCE_TAB_GROUPS = ${tuple(Object.keys(inferenceTabGroups))}
SAMPLE_BATCH_SIZE = ${SAMPLE_BATCH_SIZE}
BACKGROUND_READ_PAUSE_MS = ${BACKGROUND_READ_PAUSE_MS}
SAMPLE_SLICE_MS = ${SAMPLE_SLICE_MS}
SPAN_LOOKAHEAD_MS = ${SPAN_LOOKAHEAD_MS}
OVERVIEW_NAMES = ${tuple(new Set([...overview, ...dispatch].map((s) => s.name).concat(overviewEvents)))}
OVERVIEW_SIGNALS = ${sql([...new Set(overview.map(predicate))])}
DETAIL_SIGNALS = {
${details.map(([id, fields]) => '    ' + JSON.stringify(id) + ': ' +
  sql(fields.map(predicate)).replaceAll('\n', '\n    ') + ',').join('\n')}
}
DETAIL_NAMES = {
${details.map(([id, fields]) => {
  const names = [...new Set(fields.flatMap(({ name, countName }) => countName ? [name, countName] : [name]))];
  const items = names.length === 1 ? '(' + JSON.stringify(names[0]) + ',)' : tuple(names).replaceAll('\n', '\n    ');
  return '    ' + JSON.stringify(id) + ': ' + items + ',';
}).join('\n')}
}
DETAIL_SERIES_COUNTS = {
${details.map(([id, fields]) => '    ' + JSON.stringify(id) + ': ' + fields.length + ',').join('\n')}
}
CUMULATIVE_PAIRS = {
${fields.filter((s) => s.countName).map(({ name, countName }) =>
  '    ' + JSON.stringify(name) + ': ' + JSON.stringify(countName) + ',').join('\n')}
}
DISPATCH_WAITS = ${sql(dispatch.map(predicate))}
DRIVER_MARKERS = ${sql(markers)}
DRIVER_LINE_PATTERNS = ${tuple(driverLinePatterns.map((pattern) => pattern.source))}
DRIVER_TIMESTAMP = ${JSON.stringify(driverTimestamp.source)}
ATTRIBUTE_FIELDS = ${tuple(attributes)}
BODY_FIELDS = ${tuple(body)}
CUMULATIVE_NAMES = ${tuple(new Set(counters))}
SNAPSHOT_NAMES = ${tuple(new Set(fields.filter((s) => s.transform === 'engineSnapshots').map((s) => s.name)))}
`;
const path = new URL('../backend/query_contract.py', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) {
    throw new Error('Update backend/query_contract.py with npm run sync-query-contract.');
  }
} else {
  writeFileSync(path, output);
}
